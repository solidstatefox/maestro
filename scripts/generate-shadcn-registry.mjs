/** Generated shadcn registry for Maestro XSLT component rendering.
 * Run at build time, after installing or upgrading shadcn components.
 * No imports are executed during discovery: only source exports are examined.
 */
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const components = join(root, 'src/components/ui');
const output = join(root, 'src/components/generated/maestro-component-registry.tsx');
const files = (await readdir(components)).filter((file) => file.endsWith('.tsx')).sort();
const discovered = new Map();
for (const file of files) {
  const source = await readFile(join(components, file), 'utf8');
  const names = new Set();
  for (const match of source.matchAll(/export\s+(?:declare\s+)?(?:const|function|class)\s+([A-Z][A-Za-z0-9]*)\b/g)) names.add(match[1]);
  for (const match of source.matchAll(/export\s*\{([^}]+)\}/g)) {
    for (const rawName of match[1].split(',')) {
      const name = rawName.trim().split(/\s+as\s+/).at(-1)?.trim();
      if (name && /^[A-Z][A-Za-z0-9]*$/.test(name)) names.add(name);
    }
  }
  // React component identifiers start with capital letters. Ignore TS types and icon constants.
  for (const name of names) {
    if (new RegExp('(?:interface|type)\\s+' + name + '\\b').test(source) && !new RegExp('(?:const|function|class)\\s+' + name + '\\b').test(source)) continue;
    if (discovered.has(name)) throw new Error(`Ambiguous shadcn component ${name}: ${file} and ${discovered.get(name)}`);
    discovered.set(name, file.replace(/\.tsx$/, ''));
  }
}
const entries = [...discovered.entries()].sort(([a],[b]) => a.localeCompare(b));
const code = `/* AUTO-GENERATED by scripts/generate-shadcn-registry.mjs. Do not edit. */
"use client";
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

// Browser-only loading supports map engines and other DOM-dependent shadcn widgets.
// Type validation remains the responsibility of the XSLT component renderer.
export const maestroComponentRegistry: Readonly<Record<string, ComponentType<any>>> = {
${entries.map(([name, module]) => `  ${JSON.stringify(name.toLowerCase())}: dynamic(() => import("@/components/ui/${module}").then((m) => ({ default: m.${name} as ComponentType<any> })), { ssr: false }),`).join('\n')}
};
export const maestroComponentNames = ${JSON.stringify(entries.map(([name])=>name))} as const;
`;
await mkdir(join(root,'src/components/generated'), {recursive:true});
await writeFile(output,code);
console.log(`Maestro: generated ${entries.length} component entries from ${files.length} shadcn UI files.`);
