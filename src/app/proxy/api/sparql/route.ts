function isSafeIri(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= 4096 &&
    !/[<>"{}|^`\\\u0000-\u0020]/.test(value);
}

type RecordSelectTerm = { iri?: unknown; termType?: unknown; datatype?: unknown; lang?: unknown };

function safeRecordSelectTerm(term: RecordSelectTerm): string | null {
  const { iri, termType = "uri", lang } = term;
  const datatype = term.datatype === "string" ? undefined : term.datatype;
  if (termType === "uri") return isSafeIri(iri) ? `<${iri}>` : null;
  if (termType !== "literal" || typeof iri !== "string" || iri.length > 4096 ||
      /[\u0000-\u001f]/.test(iri) || (datatype !== undefined && !isSafeIri(datatype)) ||
      (lang !== undefined && (typeof lang !== "string" || !/^[A-Za-z]+(?:-[A-Za-z0-9]+)*$/.test(lang))) ||
      (datatype && lang)) return null;
  const lexical = JSON.stringify(iri);
  return lang ? `${lexical}@${lang}` : datatype ? `${lexical}^^<${datatype}>` : lexical;
}

function uniqueIris(value: unknown, max: number): string[] | null {
  if (!Array.isArray(value) || value.length > max || !value.every(isSafeIri)) return null;
  return [...new Set(value)];
}

function iriList(values: string[]): string {
  return values.map((value) => `<${value}>`).join(" ");
}

function buildFacetIntersectionQuery(sourceQuery: string, candidates: string[]): { query: string; variable: string } | null {
  const sparql = decodeSparqlHtmlEntities(sourceQuery).trim();
  if (!sparql || sparql.length > 100_000 || !/\bSELECT\b/i.test(sparql)) return null;
  // This route only accepts the read-only SELECT generated by the FCT facet widget.
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH)\b/i.test(sparql)) return null;

  const selectMatch = sparql.match(/\bSELECT\s+(?:(?:DISTINCT|REDUCED)\s+)?([\s\S]*?)(?:\bWHERE\s*)?\{/i);
  if (!selectMatch) return null;
  const variableMatch = selectMatch[1].match(/\?([A-Za-z_][A-Za-z0-9_]*)/);
  if (!variableMatch) return null;
  const variable = variableMatch[1];

  // Insert a VALUES restriction into the original query's outer WHERE group. This
  // preserves the generated query's graph patterns and computes the actual set
  // intersection at the SPARQL endpoint, rather than intersecting in the browser.
  const selectEnd = selectMatch.index ?? 0;
  const whereMatch = /\bWHERE\s*\{/ig;
  whereMatch.lastIndex = selectEnd;
  const explicitWhere = whereMatch.exec(sparql);
  let openBrace = -1;
  if (explicitWhere) {
    openBrace = explicitWhere.index + explicitWhere[0].lastIndexOf("{");
  } else {
    const brace = sparql.indexOf("{", selectEnd);
    openBrace = brace;
  }
  if (openBrace < 0) return null;

  const values = `\n  VALUES ?${variable} { ${iriList(candidates)} }\n`;
  return {
    query: `${sparql.slice(0, openBrace + 1)}${values}${sparql.slice(openBrace + 1)}`,
    variable,
  };
}

/**
 * Build a temporary aggregate query from the scope-correct SPARQL generated by
 * the FCT text view. FCT's generated SELECT projects the current result resource
 * first (normally ?s1); counting distinct values of that variable gives the
 * number of resources matching the current Properties/Roles scope.
 *
 * This is intentionally a narrow translator for read-only FCT-generated SELECT
 * queries, not a general SPARQL query rewriter. Native FCT list-count should
 * replace this workaround once the local /sparql endpoint is fixed.
 */
function decodeSparqlHtmlEntities(sourceQuery: string): string {
  return sourceQuery
    .replace(/&#39;|&#x27;/gi, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&amp;/gi, "&");
}

function validateFacetValueCountQuery(query: string): string | null {
  const sparseQuery = query.trim();
  if (!sparseQuery || sparseQuery.length > 100_000) return null;

  // FCT-generated Virtuoso queries may start with BASE, PREFIX, and/or DEFINE
  // prologue declarations. Validate the SELECT shape after those declarations,
  // but forward the original query unchanged so graph settings and prefixes
  // are preserved at the endpoint.
  let selectQuery = sparseQuery;
  while (true) {
    selectQuery = selectQuery.trimStart();
    const prologue = selectQuery.match(
      /^(?:BASE\s+<[^>]*>|PREFIX\s+(?:[A-Za-z_][A-Za-z0-9_-]*)?:\s*<[^>]*>|DEFINE\s+[A-Za-z_][A-Za-z0-9_-]*:[A-Za-z_][A-Za-z0-9_-]*\s+(?:<[^>]*>|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[^\s]+))\s*/i,
    );
    if (!prologue) break;
    selectQuery = selectQuery.slice(prologue[0].length);
  }

  // The client owns query construction. The proxy accepts only the scalar
  // COUNT query shape for this operation and forwards it unchanged.
  if (!/^SELECT\s*\(\s*COUNT\s*\(\s*(?:DISTINCT\s+\?[A-Za-z_][A-Za-z0-9_]*|\*)\s*\)\s+AS\s+\?ct\s*\)\s+WHERE\s*\{/i.test(selectQuery)) return null;
  // Ignore operation-looking words inside RDF IRIs, string literals, and
  // comments. Count text searches may legitimately contain terms such as
  // "with", "delete", or "create"; they are not SPARQL update operations.
  const syntaxOnly = sparseQuery.replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|<[^>]*>|#[^\r\n]*/g, " ");
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH|UPDATE)\b/i.test(syntaxOnly)) return null;
  return sparseQuery;
}

/** Diagnostic headers exposed to Chrome for this proxy's upstream SPARQL request. */
function upstreamDiagnosticHeaders(response: Response): Record<string, string> {
  if (response.headers.get("x-maestro-cache-hit") === "true") {
    // A cached body has no current upstream HTTP status or execution metadata.
    return { "X-Maestro-Upstream-Source": "cache" };
  }
  const headers: Record<string, string> = {
    "X-Maestro-Upstream-Source": "network",
    "X-Maestro-Upstream-Status": String(response.status),
  };
  for (const [upstream, diagnostic] of [
    ["x-sql-state", "X-Maestro-Upstream-SQL-State"],
    ["x-sql-message", "X-Maestro-Upstream-SQL-Message"],
    ["x-exec-milliseconds", "X-Maestro-Upstream-Exec-Milliseconds"],
    ["x-exec-db-activity", "X-Maestro-Upstream-DB-Activity"],
    ["x-sparql-anytime", "X-Maestro-Upstream-SPARQL-Anytime"],
  ] as const) {
    const value = response.headers.get(upstream);
    if (value) headers[diagnostic] = value;
  }
  return headers;
}

function sparqlResponseHeaders(response: Response, incomplete: boolean): Record<string, string> {
  return { ...anytimeResponseHeaders(response, incomplete), ...upstreamDiagnosticHeaders(response) };
}

type SparqlQueryResult = { responseText: string; response: Response; key: string };
const inFlightSparqlRequests = new Map<string, Promise<SparqlQueryResult>>();

function parseSparqlResults(responseText: string): {
  head: { vars: string[] };
  results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
} | null {
  try {
    const parsed: unknown = JSON.parse(responseText);
    if (!parsed || typeof parsed !== "object") return null;
    const value = parsed as {
      head?: { vars?: unknown };
      results?: { bindings?: unknown };
    };
    if (!value.head || !Array.isArray(value.head.vars) ||
        !value.head.vars.every((item) => typeof item === "string") ||
        !value.results || !Array.isArray(value.results.bindings)) return null;
    for (const binding of value.results.bindings) {
      if (!binding || typeof binding !== "object" || Array.isArray(binding)) return null;
      for (const term of Object.values(binding as Record<string, unknown>)) {
        if (!term || typeof term !== "object" || Array.isArray(term) ||
            typeof (term as { value?: unknown }).value !== "string" ||
            typeof (term as { type?: unknown }).type !== "string") return null;
      }
    }
    return value as {
      head: { vars: string[] };
      results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
    };
  } catch {
    return null;
  }
}

async function querySparql(endpoint: string, query: string, configuredTimeoutMs?: number): Promise<SparqlQueryResult> {
  const timeoutMs = configuredTimeoutMs ?? 20000;
  const sparqlUrl = endpoint;
  const key = queryCacheKey("sparql", sparqlUrl.toString(), query);
  const pendingKey = `${key}:${timeoutMs}`;
  const cached = getQueryCache<string>(key);
  if (cached !== undefined) {
    return {
      responseText: cached,
      response: new Response(cached, {
        status: 200,
        headers: { "Content-Type": "application/sparql-results+json; charset=utf-8", "X-Maestro-Cache-Hit": "true" },
      }),
      key,
    };
  }

  // Coalesce identical upstream requests, but never cache here: the caller must
  // validate the operation-specific result before it becomes shared cache data.
  const pending = inFlightSparqlRequests.get(pendingKey);
  if (pending) return pending;

  const requestPromise = (async () => {
    const response = await fetch(sparqlUrl, {
      method: "POST",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded; charset=UTF-8",
        Accept: "application/sparql-results+json, application/json;q=0.9",
      },
      body: new URLSearchParams({ query, ...(configuredTimeoutMs ? { timeout: String(configuredTimeoutMs) } : {}) }).toString(),
      cache: "no-store",
      signal: AbortSignal.timeout(timeoutMs),
    });
    return { responseText: await response.text(), response, key };
  })();
  inFlightSparqlRequests.set(pendingKey, requestPromise);
  try {
    return await requestPromise;
  } finally {
    if (inFlightSparqlRequests.get(pendingKey) === requestPromise) inFlightSparqlRequests.delete(pendingKey);
  }
}

/** Expand Node/Undici fetch errors, whose top-level message is often only "fetch failed". */
function describeProxyError(error: unknown, depth = 0): Record<string, unknown> {
  if (!(error instanceof Error)) {
    if (error && typeof error === "object") {
      const record = error as Record<string, unknown>;
      return Object.fromEntries(Object.entries(record).map(([key, value]) => [
        key,
        value instanceof Error ? describeProxyError(value, depth + 1) : value,
      ]));
    }
    return { value: String(error) };
  }
  const detail: Record<string, unknown> = { name: error.name, message: error.message };
  if (error.stack) detail.stack = error.stack;
  const nodeError = error as Error & { code?: unknown; errno?: unknown; syscall?: unknown; hostname?: unknown; address?: unknown; port?: unknown; cause?: unknown };
  for (const key of ["code", "errno", "syscall", "hostname", "address", "port"] as const) {
    if (nodeError[key] !== undefined) detail[key] = nodeError[key];
  }
  if (nodeError.cause !== undefined && depth < 4) {
    detail.cause = nodeError.cause instanceof Error
      ? describeProxyError(nodeError.cause, depth + 1)
      : String(nodeError.cause);
  }
  return detail;
}

function safeEndpointForDiagnostics(endpoint: string): string {
  try {
    const url = new URL(endpoint);
    url.username = "";
    url.password = "";
    return url.toString();
  } catch {
    return endpoint;
  }
}

export async function POST(request: Request) {
  logProxyCaller(request, "sparql.POST");
  let diagnosticEndpoint = "";
  let diagnosticOperation = "parse request";
  let diagnosticQuery = "";
  // Browser preferences are bounded and only control this request's execution time.
  const requestedMs = Number(request.headers.get("x-maestro-query-timeout-ms"));
  const queryTimeoutMs = Number.isInteger(requestedMs) && requestedMs >= 1000 && requestedMs <= 120000 ? requestedMs : undefined;
  try {
    const body = await request.json().catch(() => null);
    const endpointList = await getConfiguredFctEndpoints(request);
    const selectedEndpoint = selectConfiguredFctEndpoint(request, endpointList);
    const fctEndpoint = selectedEndpoint?.url;
    diagnosticEndpoint = fctEndpoint ?? "";
    if (!fctEndpoint) {
      return NextResponse.json({ error: "No graphs are configured in SITE_SPARQL_ENDPOINTS." }, { status: 503 });
    }

    // Resolve still-missing URI labels only in named graphs that the existing
    // Record graph dropdown has already discovered. This is a separate, bounded
    // operation: the initial Record SELECT never waits for graph enumeration.
    if (body?.recordValueLabels && typeof body.recordValueLabels === "object") {
      const { uris, graphs, preferredLanguage } = body.recordValueLabels as { uris?: unknown; graphs?: unknown; preferredLanguage?: unknown };
      const resources = uniqueIris(uris, 128);
      const namedGraphs = uniqueIris(graphs, 500);
      if (!resources || !namedGraphs || resources.length === 0 || namedGraphs.length === 0 ||
          typeof preferredLanguage !== "string" || !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(preferredLanguage)) {
        return NextResponse.json({ error: "Record label enrichment requires URI values and discovered graph IRIs." }, { status: 400 });
      }
      const query = `SELECT DISTINCT ?labelResource ?labelPredicate ?label WHERE {
        VALUES ?labelResource { ${iriList(resources)} }
        VALUES ?labelGraph { ${iriList(namedGraphs)} }
        VALUES ?labelPredicate {
          <http://www.w3.org/2000/01/rdf-schema#label>
          <http://www.w3.org/2004/02/skos/core#prefLabel>
          <http://schema.org/name>
          <https://schema.org/name>
          <http://xmlns.com/foaf/0.1/name>
          <http://purl.org/dc/terms/title>
        }
        GRAPH ?labelGraph { ?labelResource ?labelPredicate ?label . }
        FILTER(isLiteral(?label) && (LANG(?label) = "" || LANGMATCHES(LANG(?label), ${JSON.stringify(preferredLanguage)})))
      }`;
      diagnosticOperation = "Record URI labels in discovered graphs";
      diagnosticQuery = query;
      const { responseText, response, key } = await querySparql(fctEndpoint, query, queryTimeoutMs);
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (!response.ok && !incomplete) {
        return NextResponse.json({ error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}: ${responseText.trim().slice(0, 1000)}` }, { status: response.status, headers: upstreamDiagnosticHeaders(response) });
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed) return NextResponse.json({ error: "Invalid Record label SELECT results JSON." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, incomplete, query }, {
        headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
      });
    }

    // A SELECT result's blank-node label cannot be reused as a SPARQL term.
    // Instead, compile a list-values FCT query derived from the original Results
    // path: it binds each definition blank node in ?c1 while constraining the
    // actual reverse-role node to the parent URI shown on the Results badge.
    // The Record properties are projected inside the SAME request so that
    // blank-node identity is never compared between independent result sets.
    if (body?.recordBlankNodes && typeof body.recordBlankNodes === "object") {
      const { queryXml, parent, predicate, preferredLanguage, limit, graphs } = body.recordBlankNodes as {
        queryXml?: unknown; parent?: unknown; predicate?: unknown;
        preferredLanguage?: unknown; limit?: unknown; graphs?: unknown;
      };
      const namedGraphs = graphs === undefined ? [] : uniqueIris(graphs, 500);
      if (!isSafeIri(parent) || !isSafeIri(predicate) || !namedGraphs ||
          typeof queryXml !== "string" || queryXml.length > 100_000 ||
          typeof preferredLanguage !== "string" || !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(preferredLanguage) ||
          typeof limit !== "number" || !Number.isInteger(limit) || limit < 1 || limit > 10000) {
        return NextResponse.json({ error: "A scoped list-values FCT query, URI parent, predicate, preferred language, limit (1–10000), and valid graph list are required." }, { status: 400 });
      }
      let compiled;
      try {
        compiled = compileFctXmlToSparql(queryXml);
        if (compiled.view !== "list-values" || compiled.limit > limit || compiled.offset !== 0 ||
            !queryXml.includes(parent) || !queryXml.includes(predicate)) {
          throw new Error("The blank-node Record query must be a bounded, parent-constrained list-values query.");
        }
      } catch (error) {
        return NextResponse.json({ error: `Invalid blank-node list-values query: ${error instanceof Error ? error.message : String(error)}` }, { status: 400 });
      }
      // Virtuoso DEFINE/PREFIX directives must be outside the nested SELECT.
      const compiledText = compiled.query.trim();
      const preambleMatch = compiledText.match(/^((?:(?:DEFINE|PREFIX|BASE)\s+[^\n]*\n)*)/i);
      const preamble = preambleMatch?.[1] ?? "";
      const innerSelect = compiledText.slice(preamble.length).trim();
      if (!/^SELECT\b/i.test(innerSelect)) {
        return NextResponse.json({ error: "The FCT list-values compiler did not generate a SELECT query." }, { status: 400 });
      }
      // A blank-node Record exposes both outgoing properties and incoming roles.
      // Both branches use the *same* bound ?node from the FCT-derived SELECT;
      // result-set-local blank-node labels are never interpolated into queries.
      // Avoid joining the two directions together (which would multiply rows).
      const recordGraphPrefix = namedGraphs.length ? `VALUES ?recordGraph { ${iriList(namedGraphs)} } ` : "";
      const outgoingPattern = namedGraphs.length
        ? `${recordGraphPrefix}GRAPH ?recordGraph { ?node ?predicate ?object . }`
        : `?node ?predicate ?object .`;
      const incomingPattern = namedGraphs.length
        ? `${recordGraphPrefix}GRAPH ?recordGraph { ?object ?predicate ?node . }`
        : `?object ?predicate ?node .`;
      const query = `${preamble}SELECT ?node ?direction ?predicate ?object WHERE {
        { ${innerSelect} }
        BIND(?c1 AS ?node)
        FILTER(isBlank(?node))
        OPTIONAL {
          {
            ${outgoingPattern}
            FILTER(!isLiteral(?object) || LANG(?object) = "" || LANGMATCHES(LANG(?object), ${JSON.stringify(preferredLanguage)}))
            BIND("property" AS ?direction)
          }
          UNION
          {
            ${incomingPattern}
            BIND("property-of" AS ?direction)
          }
        }
      } LIMIT ${limit}`;
      diagnosticOperation = "FCT-path blank-node Record SELECT";
      diagnosticQuery = query;
      const { responseText, response, key } = await querySparql(fctEndpoint, query, queryTimeoutMs);
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (!response.ok && !incomplete) {
        return NextResponse.json({ error: `SPARQL endpoint returned HTTP ${response.status}: ${responseText.trim().slice(0, 1000)}` }, { status: response.status, headers: upstreamDiagnosticHeaders(response) });
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed) return NextResponse.json({ error: "Invalid scoped blank-node Record SELECT response." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, incomplete, query }, {
        headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
      });
    }

    // One authoritative, language-filtered Record snapshot. This query does not
    // join labels: URI display names are enriched asynchronously and are not
    // Record triples. Filter inside WHERE, BEFORE LIMIT, so the limit counts
    // eligible triples rather than multilingual values that will be discarded.
    if (body?.recordSelect && typeof body.recordSelect === "object") {
      const { iri, termType = "uri", datatype, lang, limit, graphs, focusPredicate, preferredLanguage } = body.recordSelect as RecordSelectTerm & { limit?: unknown; graphs?: unknown; focusPredicate?: unknown; preferredLanguage?: unknown };
      const namedGraphs = graphs === undefined ? [] : uniqueIris(graphs, 500);
      const record = safeRecordSelectTerm({ iri, termType, datatype, lang });
      if (!record || !Number.isInteger(limit) || typeof limit !== "number" || limit < 1 || limit > 10000 || !namedGraphs ||
          (focusPredicate !== undefined && !isSafeIri(focusPredicate)) ||
          (typeof preferredLanguage !== "string" || !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(preferredLanguage))) {
        return NextResponse.json({ error: "A valid Record RDF term, preferred language, limit (1–10000), and optional graph IRI list are required." }, { status: 400 });
      }
      const graphPrefix = namedGraphs.length ? `VALUES ?recordGraph { ${iriList(namedGraphs)} } GRAPH ?recordGraph { ` : "";
      const graphSuffix = namedGraphs.length ? " }" : "";
      // JSON.stringify escapes the validated BCP-47 language for SPARQL.
      const allowedLiteral = `FILTER(!isLiteral(?object) || LANG(?object) = "" || LANGMATCHES(LANG(?object), ${JSON.stringify(preferredLanguage)}))`;
      // Literal focus nodes have only incoming roles. The object is the focus
      // literal itself, so no language filtering is applied to the focus term.
      let query = termType === "literal"
        ? `SELECT ?subject ?predicate ?object WHERE {
             { SELECT ?subject ?predicate WHERE {
                 ${graphPrefix}?subject ?predicate ${record} .${graphSuffix}
               } LIMIT ${limit} }
             BIND(${record} AS ?object)
           }`
        : `SELECT ?subject ?predicate ?object WHERE {
             ${graphPrefix}
               { ${record} ?predicate ?object . BIND(${record} AS ?subject) }
               UNION { ?subject ?predicate ${record} . BIND(${record} AS ?object) }
             ${graphSuffix}
             ${allowedLiteral}
           } LIMIT ${limit}`;
      diagnosticOperation = termType === "literal" ? "Literal Record incoming Roles" : "Language-filtered Record SELECT";
      diagnosticQuery = query;
      let result: SparqlQueryResult;
      let focusedFallback = false;
      try {
        // Don't make the user wait a full 20 seconds for a global Roles scan
        // when the focus property already establishes a useful incoming role.
        const scanTimeout = termType === "literal" && focusPredicate
          ? Math.min(queryTimeoutMs ?? 20000, 5000) : queryTimeoutMs;
        result = await querySparql(fctEndpoint, query, scanTimeout);
      } catch (error) {
        if (termType !== "literal" || !focusPredicate ||
            !/timeout|abort|UND_ERR_CONNECT_TIMEOUT/i.test(String(error instanceof Error ? error.message + " " + String(error.cause) : error))) throw error;
        focusedFallback = true;
        query = `SELECT ?subject ?predicate ?object WHERE {
          { SELECT ?subject WHERE {
            ${graphPrefix}?subject <${focusPredicate}> ${record} .${graphSuffix}
          } LIMIT ${limit} }
          BIND(<${focusPredicate}> AS ?predicate)
          BIND(${record} AS ?object)
        }`;
        diagnosticQuery = query;
        result = await querySparql(fctEndpoint, query, queryTimeoutMs);
      }
      const { responseText, response, key } = result;
      const incomplete = focusedFallback || response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (!response.ok && !incomplete) {
        return NextResponse.json({ error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}: ${responseText.trim().slice(0, 1000)}` }, { status: response.status, headers: upstreamDiagnosticHeaders(response) });
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed && !incomplete) return NextResponse.json({ error: "Invalid Record SELECT results JSON." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      if (parsed && !["subject", "predicate", "object"].every((name) => parsed.head.vars.includes(name))) {
        return NextResponse.json({ error: "Record SELECT response lacks RDF triple columns." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete && parsed) setQueryCache(key, responseText);
      return NextResponse.json({ ...(parsed ?? { head: { vars: [] }, results: { bindings: [] } }), incomplete, query }, {
        headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
      });
    }

    // The Results pane compiles the authoritative FCT query tree to SPARQL on
    // the client and submits that SELECT here; unlike /fct, this path returns
    // the endpoint's SPARQL result bindings directly.
    if (body?.resultsQuery && typeof body.resultsQuery === "object") {
      const resultsQuery = body.resultsQuery.sparql;
      if (typeof resultsQuery !== "string" || !/^\s*(?:DEFINE\s+[^\n]+\s+)*SELECT\b/i.test(resultsQuery) ||
          !/\bAS\s+\?c1\b/i.test(resultsQuery) || /\b(?:INSERT|DELETE|CLEAR|LOAD|CREATE|DROP|MOVE|COPY|ADD)\b/i.test(resultsQuery)) {
        return NextResponse.json({ error: "A client-generated SELECT Results SPARQL query with ?c1 is required." }, { status: 400 });
      }
      diagnosticOperation = "Results SPARQL query";
      diagnosticQuery = resultsQuery;
      const { responseText, response, key } = await querySparql(fctEndpoint, resultsQuery, queryTimeoutMs);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText) ?? (incomplete ? { head: { vars: ["c1"] }, results: { bindings: [] } } : null);
      if (!parsed || !parsed.head.vars.includes("c1")) {
        return NextResponse.json({ error: "Virtuoso returned invalid Results SPARQL JSON (expected ?c1)." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, query: resultsQuery, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    if (body?.facetValueCount && typeof body.facetValueCount === "object") {
      const sourceQuery = body.facetValueCount.sparql;
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The client-generated scalar count SPARQL query is required." }, { status: 400 });
      }
      const countQuery = validateFacetValueCountQuery(sourceQuery);
      if (!countQuery) {
        return NextResponse.json({ error: "The client must provide a scalar COUNT(...) AS ?ct SPARQL query." }, { status: 400 });
      }

      diagnosticOperation = "facet value count SPARQL query";
      diagnosticQuery = countQuery;
      const { responseText, response, key } = await querySparql(fctEndpoint, countQuery, queryTimeoutMs);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText);
      if (!parsed && incomplete) return NextResponse.json({ incomplete: true, query: countQuery }, { headers: sparqlResponseHeaders(response, true) });
      const countValue = parsed?.results.bindings[0]?.ct?.value;
      const count = countValue !== undefined && /^\d+$/.test(countValue) ? Number(countValue) : NaN;
      if (!parsed || !parsed.head.vars.includes("ct") || parsed.results.bindings.length !== 1 ||
          !Number.isSafeInteger(count) || count < 0) {
        if (incomplete) return NextResponse.json({ incomplete: true, query: countQuery }, { headers: sparqlResponseHeaders(response, true) });
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL count result." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ count, query: countQuery, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    if (body?.facetIntersection && typeof body.facetIntersection === "object") {
      const sourceQuery = body.facetIntersection.sparql;
      const candidates = uniqueIris(body.facetIntersection.candidates, 500);
      if (!candidates) {
        return NextResponse.json({ error: "Autoconfigure candidates must be valid IRIs (maximum 500)." }, { status: 400 });
      }
      if (!candidates.length) return NextResponse.json({ uris: [] });
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The generated facet SPARQL query is required." }, { status: 400 });
      }
      const built = buildFacetIntersectionQuery(sourceQuery, candidates);
      if (!built) {
        return NextResponse.json({ error: "Could not safely add the high-frequency facets to the generated SPARQL query." }, { status: 400 });
      }

      diagnosticOperation = "facet intersection SPARQL query";
      diagnosticQuery = built.query;
      const { responseText, response, key } = await querySparql(fctEndpoint, built.query, queryTimeoutMs);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText) ?? (incomplete ? { head: { vars: [built.variable] }, results: { bindings: [] } } : null);
      if (!parsed || !parsed.head.vars.includes(built.variable)) {
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL facet-intersection result." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      const bindings = parsed.results.bindings;
      const uris = [...new Set(bindings
        .map((binding) => binding[built.variable]?.value)
        .filter((value): value is string => typeof value === "string" && value.length > 0))];
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ uris, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    // Results enrichment is intentionally bounded to exact FCT result URIs and
    // the selected relationships, rather than accepting arbitrary SPARQL.
    const resources = uniqueIris(body?.resources, 100);
    const properties = uniqueIris(body?.properties ?? [], 100);
    const roles = uniqueIris(body?.roles ?? [], 100);
    if (!resources || resources.length === 0) {
      return NextResponse.json({ error: "One or more valid FCT result resource URIs are required." }, { status: 400 });
    }
    if (!properties || !roles) {
      return NextResponse.json({ error: "Selected property and role lists must contain valid IRIs (maximum 100 each)." }, { status: 400 });
    }
    if (properties.length + roles.length === 0) {
      return NextResponse.json({ head: { vars: [] }, results: { bindings: [] } });
    }

    const resourceValues = iriList(resources);
    const branches: string[] = [];
    if (properties.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(properties)} } ?resource ?property ?value . BIND("forward" AS ?direction) }`);
    }
    if (roles.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(roles)} } ?value ?property ?resource . BIND("reverse" AS ?direction) }`);
    }
    const query = `SELECT DISTINCT ?resource ?property ?direction ?value WHERE { ${branches.join(" UNION ")} }`;
    diagnosticOperation = "result relationship enrichment SPARQL query";
    diagnosticQuery = query;
    const { responseText, response, key } = await querySparql(fctEndpoint, query, queryTimeoutMs);
    const contentType = response.headers.get("content-type") ?? "";
    if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
      proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
      return NextResponse.json(
        { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
        { status: response.status, headers: upstreamDiagnosticHeaders(response) },
      );
    }
    if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
      return NextResponse.json(
        { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${responseText.trim().slice(0, 1000)}` : "."}`, details: responseText },
        { status: response.status, headers: upstreamDiagnosticHeaders(response) },
      );
    }

    const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
    if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
    const parsed = parseSparqlResults(responseText);
    if (!parsed && !incomplete) {
      return NextResponse.json({ error: "Virtuoso returned invalid SPARQL results JSON." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
    }
    if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
    return NextResponse.json(parsed ? { ...parsed, incomplete } : { head: { vars: [] }, results: { bindings: [] }, incomplete: true }, {
      status: 200,
      headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
    });
  } catch (error) {
    const diagnostics = {
      route: "sparql.POST",
      operation: diagnosticOperation,
      endpoint: diagnosticEndpoint ? safeEndpointForDiagnostics(diagnosticEndpoint) : null,
      query: diagnosticQuery || null,
      error: describeProxyError(error),
    };
    proxyLog("error", "sparql.POST.failed", { operation: diagnosticOperation, endpoint: diagnostics.endpoint, error: diagnostics.error, err: error });
    return proxyFailure(request, "sparql.POST", error, { operation: diagnosticOperation, endpoint: diagnostics.endpoint });
  }
}