function isSafeIri(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= 4096 &&
    !/[<>"{}|^`\\\u0000-\u0020]/.test(value);
}

type RecordSelectTerm = { iri?: unknown; termType?: unknown; datatype?: unknown; lang?: unknown };

function safeRecordSelectTerm(term: RecordSelectTerm): string | null {
  const { iri, termType = "uri", lang } = term;
  const datatype = term.datatype === "string" ? undefined : term.datatype;
  if (termType === "uri") return isSafeIri(iri) ? `<${iri}>` : null;
  if (termType !== "literal" || typeof iri !== "string" || iri.length > 4096 ||
      /[\u0000-\u001f]/.test(iri) || (datatype !== undefined && !isSafeIri(datatype)) ||
      (lang !== undefined && (typeof lang !== "string" || !/^[A-Za-z]+(?:-[A-Za-z0-9]+)*$/.test(lang))) ||
      (datatype && lang)) return null;
  const lexical = JSON.stringify(iri);
  return lang ? `${lexical}@${lang}` : datatype ? `${lexical}^^<${datatype}>` : lexical;
}

function uniqueIris(value: unknown, max: number): string[] | null {
  if (!Array.isArray(value) || value.length > max || !value.every(isSafeIri)) return null;
  return [...new Set(value)];
}

function iriList(values: string[]): string {
  return values.map((value) => `<${value}>`).join(" ");
}

function buildFacetIntersectionQuery(sourceQuery: string, candidates: string[]): { query: string; variable: string } | null {
  const sparql = decodeSparqlHtmlEntities(sourceQuery).trim();
  if (!sparql || sparql.length > 100_000 || !/\bSELECT\b/i.test(sparql)) return null;
  // This route only accepts the read-only SELECT generated by the FCT facet widget.
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH)\b/i.test(sparql)) return null;

  const selectMatch = sparql.match(/\bSELECT\s+(?:(?:DISTINCT|REDUCED)\s+)?([\s\S]*?)(?:\bWHERE\s*)?\{/i);
  if (!selectMatch) return null;
  const variableMatch = selectMatch[1].match(/\?([A-Za-z_][A-Za-z0-9_]*)/);
  if (!variableMatch) return null;
  const variable = variableMatch[1];

  // Insert a VALUES restriction into the original query's outer WHERE group. This
  // preserves the generated query's graph patterns and computes the actual set
  // intersection at the SPARQL endpoint, rather than intersecting in the browser.
  const selectEnd = selectMatch.index ?? 0;
  const whereMatch = /\bWHERE\s*\{/ig;
  whereMatch.lastIndex = selectEnd;
  const explicitWhere = whereMatch.exec(sparql);
  let openBrace = -1;
  if (explicitWhere) {
    openBrace = explicitWhere.index + explicitWhere[0].lastIndexOf("{");
  } else {
    const brace = sparql.indexOf("{", selectEnd);
    openBrace = brace;
  }
  if (openBrace < 0) return null;

  const values = `\n  VALUES ?${variable} { ${iriList(candidates)} }\n`;
  return {
    query: `${sparql.slice(0, openBrace + 1)}${values}${sparql.slice(openBrace + 1)}`,
    variable,
  };
}

/**
 * Build a temporary aggregate query from the scope-correct SPARQL generated by
 * the FCT text view. FCT's generated SELECT projects the current result resource
 * first (normally ?s1); counting distinct values of that variable gives the
 * number of resources matching the current Properties/Roles scope.
 *
 * This is intentionally a narrow translator for read-only FCT-generated SELECT
 * queries, not a general SPARQL query rewriter. Native FCT list-count should
 * replace this workaround once the local /sparql endpoint is fixed.
 */
function decodeSparqlHtmlEntities(sourceQuery: string): string {
  return sourceQuery
    .replace(/&#39;|&#x27;/gi, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&amp;/gi, "&");
}

function validateFacetValueCountQuery(query: string, numericDomain = false, temporalDomain = false): string | null {
  const sparseQuery = query.trim();
  if (!sparseQuery || sparseQuery.length > 100_000) return null;

  // FCT-generated Virtuoso queries may start with BASE, PREFIX, and/or DEFINE
  // prologue declarations. Validate the SELECT shape after those declarations,
  // but forward the original query unchanged so graph settings and prefixes
  // are preserved at the endpoint.
  let selectQuery = sparseQuery;
  while (true) {
    selectQuery = selectQuery.trimStart();
    const prologue = selectQuery.match(
      /^(?:BASE\s+<[^>]*>|PREFIX\s+(?:[A-Za-z_][A-Za-z0-9_-]*)?:\s*<[^>]*>|DEFINE\s+[A-Za-z_][A-Za-z0-9_-]*:[A-Za-z_][A-Za-z0-9_-]*\s+(?:<[^>]*>|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[^\s]+))\s*/i,
    );
    if (!prologue) break;
    selectQuery = selectQuery.slice(prologue[0].length);
  }

  // The client owns query construction. The proxy accepts only the scalar
  // COUNT query shape for this operation and forwards it unchanged.
  const scalarCount = /^SELECT\s*\(\s*COUNT\s*\(\s*(?:DISTINCT\s+\?[A-Za-z_][A-Za-z0-9_]*|\*)\s*\)\s+AS\s+\?ct\s*\)/i;
  const countPrefix = selectQuery.match(scalarCount);
  if (!countPrefix) return null;
  const remainder = selectQuery.slice(countPrefix[0].length);
  if (temporalDomain) {
    // Only the exact two ISO-day aggregates emitted by FCT's temporal builder.
    if (!/^\s*\(\s*MIN\s*\(\s*\?facetLex\s*\)\s+AS\s+\?min\s*\)\s*\(\s*MAX\s*\(\s*\?facetLex\s*\)\s+AS\s+\?max\s*\)\s+WHERE\s*\{/i.test(remainder)) return null;
  } else if (numericDomain) {
    // Only the two fixed projections emitted by the approved numeric provider.
    // Reject other expressions rather than accepting arbitrary aggregate SPARQL.
    // SPARQL does not guarantee ordering of RDF multi-valued projection
    // declarations; either MIN/MAX or MAX/MIN is valid. Require exactly one
    // of each fixed expression and alias, followed immediately by WHERE.
    const projections: Array<"min" | "max"> = [];
    let remaining = remainder;
    for (let index = 0; index < 2; index++) {
      const projection = remaining.match(/^\s*\(\s*(MIN|MAX)\s*\(\s*\?facetNumber\s*\)\s+AS\s+\?(min|max)\s*\)/i);
      if (!projection || projection[1].toLowerCase() !== projection[2].toLowerCase()) return null;
      projections.push(projection[2].toLowerCase() as "min" | "max");
      remaining = remaining.slice(projection[0].length);
    }
    if (new Set(projections).size !== 2 || !/^\s+WHERE\s*\{/i.test(remaining)) return null;
  } else if (!/^\s+WHERE\s*\{/i.test(remainder)) return null;
  // Ignore operation-looking words inside RDF IRIs, string literals, and
  // comments. Count text searches may legitimately contain terms such as
  // "with", "delete", or "create"; they are not SPARQL update operations.
  const syntaxOnly = sparseQuery.replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|<[^>]*>|#[^\r\n]*/g, " ");
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH|UPDATE)\b/i.test(syntaxOnly)) return null;
  return sparseQuery;
}

/** Diagnostic headers exposed to Chrome for this proxy's upstream SPARQL request. */
function upstreamDiagnosticHeaders(response: Response): Record<string, string> {
  if (response.headers.get("x-maestro-cache-hit") === "true") {
    // A cached body has no current upstream HTTP status or execution metadata.
    return { "X-Maestro-Upstream-Source": "cache" };
  }
  const headers: Record<string, string> = {
    "X-Maestro-Upstream-Source": "network",
    "X-Maestro-Upstream-Status": String(response.status),
  };
  for (const [upstream, diagnostic] of [
    ["x-sql-state", "X-Maestro-Upstream-SQL-State"],
    ["x-sql-message", "X-Maestro-Upstream-SQL-Message"],
    ["x-exec-milliseconds", "X-Maestro-Upstream-Exec-Milliseconds"],
    ["x-exec-db-activity", "X-Maestro-Upstream-DB-Activity"],
    ["x-sparql-anytime", "X-Maestro-Upstream-SPARQL-Anytime"],
  ] as const) {
    const value = response.headers.get(upstream);
    if (value) headers[diagnostic] = value;
  }
  return headers;
}

function sparqlResponseHeaders(response: Response, incomplete: boolean): Record<string, string> {
  return { ...anytimeResponseHeaders(response, incomplete), ...upstreamDiagnosticHeaders(response) };
}

type SparqlQueryResult = { responseText: string; response: Response; key: string };
const inFlightSparqlRequests = new Map<string, Promise<SparqlQueryResult>>();

function parseSparqlResults(responseText: string): {
  head: { vars: string[] };
  results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
} | null {
  try {
    const parsed: unknown = JSON.parse(responseText);
    if (!parsed || typeof parsed !== "object") return null;
    const value = parsed as {
      head?: { vars?: unknown };
      results?: { bindings?: unknown };
    };
    if (!value.head || !Array.isArray(value.head.vars) ||
        !value.head.vars.every((item) => typeof item === "string") ||
        !value.results || !Array.isArray(value.results.bindings)) return null;
    for (const binding of value.results.bindings) {
      if (!binding || typeof binding !== "object" || Array.isArray(binding)) return null;
      for (const term of Object.values(binding as Record<string, unknown>)) {
        if (!term || typeof term !== "object" || Array.isArray(term) ||
            typeof (term as { value?: unknown }).value !== "string" ||
            typeof (term as { type?: unknown }).type !== "string") return null;
      }
    }
    return value as {
      head: { vars: string[] };
      results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
    };
  } catch {
    return null;
  }
}

/** Only remove the top-level IRI rank sort on a verified Virtuoso sort failure.
 * Never rewrite arbitrary user SPARQL or remove a different ORDER BY clause. */
function unorderedIriRankFallback(query: string, error: string): string | null {
  if (!virtuosoRankFailure(error)) return null;
  // The FCT-derived blank-node Record SELECT nests the ranked Results SELECT.
  // Remove only the exact generated rank-only ORDER BY, including inside a
  // subquery; never remove a user's unrelated sort or its scope constraints.
  const ranking = /\bORDER\s+BY\s+DESC\s*\(\s*<LONG::IRI_RANK>\s*\(\s*\?[A-Za-z][A-Za-z0-9_]*\s*\)\s*\)\s*(?=(?:LIMIT|OFFSET|\}|$))/gi;
  const fallback = query.replace(ranking, " ");
  return fallback === query ? null : fallback;
}

async function readBoundedSparqlResponse(response: Response, maxBytes: number): Promise<string | null> {
  if (!response.body) return "";
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let bytes = 0;
  const parts: string[] = [];
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      bytes += value.byteLength;
      if (bytes > maxBytes) { await reader.cancel().catch(() => undefined); return null; }
      parts.push(decoder.decode(value, { stream: true }));
    }
    parts.push(decoder.decode());
    return parts.join("");
  } finally { reader.releaseLock(); }
}

async function querySparqlTransport(endpoint: string, query: string, configuredTimeoutMs?: number,
  requestSignal?: AbortSignal, priorityOverride?: QueryPriority, bypassCache = false,
  personalRequest?: Request, authorization?: string, writing = false, maxResponseBytes?: number): Promise<SparqlQueryResult> {
  const timeoutMs = configuredTimeoutMs ?? 20000;
  // A read has no local delivery deadline; writes retain their separate safety policy.
  const sparqlUrl = endpoint;
  const key = queryCacheKey("sparql", sparqlUrl.toString(), `${timeoutMs}\u0000${query}`);
  const pendingKey = `${currentProxyClient()}:${key}:${timeoutMs}`;
  const cached = bypassCache || authorization ? undefined : getQueryCache<string>(key);
  if (cached !== undefined) {
    return {
      responseText: cached,
      response: new Response(cached, {
        status: 200,
        headers: { "Content-Type": "application/sparql-results+json; charset=utf-8", "X-Maestro-Cache-Hit": "true" },
      }),
      key,
    };
  }

  // Coalesce identical upstream requests, but never cache here: the caller must
  // validate the operation-specific result before it becomes shared cache data.
  const pending = requestSignal || authorization ? undefined : inFlightSparqlRequests.get(pendingKey);
  if (pending) return pending;

  const requestPromise = (async () => {
    await checkGraphServerDestination(sparqlUrl);
    const result = await withGraphServerSlot(
      sparqlUrl, priorityOverride ?? (/\bCOUNT\s*\(|\bGROUP BY\b/i.test(query) ? "count" : "interactive"), requestSignal,
      () => traceVirtuosoDispatch(() => withUpstreamTransport(async () => {
      const writeDeadline = writing ? AbortSignal.timeout(timeoutMs) : undefined;
      const response = await (writing ? fetch : fetchVirtuosoRead)(sparqlUrl, {
      method: "POST",
      headers: {
        "Content-Type": writing ? "application/sparql-update" : "application/x-www-form-urlencoded; charset=UTF-8",
        Accept: writing ? "text/plain, application/json;q=0.9" : "application/sparql-results+json, application/json;q=0.9",
        ...(authorization ? { Authorization: authorization } : {}),
      },
      body: writing ? query : new URLSearchParams({ query, ...(timeoutMs >= 1000 ? { timeout: String(timeoutMs) } : {}) }).toString(),
      cache: "no-store",
      redirect: "manual",
      signal: writeDeadline ? (requestSignal ? AbortSignal.any([requestSignal, writeDeadline]) : writeDeadline) : requestSignal,
    });
      const responseText = maxResponseBytes === undefined ? await response.text() : await readBoundedSparqlResponse(response, maxResponseBytes);
      if (responseText === null) {
        const message = "Request-scoped SPARQL response exceeded the requested transport byte limit.";
        return { responseText: message, response: new Response(message, { status: 413, headers: { "X-Maestro-Response-Limit": "exceeded" } }), key };
      }
      return { responseText, response, key };
    }, requestSignal)), weightMaestroQuery(query, priorityOverride ?? (/\bCOUNT\s*\(|\bGROUP BY\b/i.test(query) ? "count" : "interactive")));
    return result;
  })();
  if (!requestSignal && !authorization) inFlightSparqlRequests.set(pendingKey, requestPromise);
  try {
    return await requestPromise;
  } finally {
    if (!requestSignal && inFlightSparqlRequests.get(pendingKey) === requestPromise) inFlightSparqlRequests.delete(pendingKey);
  }
}

/** Expand Node/Undici fetch errors, whose top-level message is often only "fetch failed". */
function describeProxyError(error: unknown, depth = 0): Record<string, unknown> {
  if (!(error instanceof Error)) {
    if (error && typeof error === "object") {
      const record = error as Record<string, unknown>;
      return Object.fromEntries(Object.entries(record).map(([key, value]) => [
        key,
        value instanceof Error ? describeProxyError(value, depth + 1) : value,
      ]));
    }
    return { value: String(error) };
  }
  const detail: Record<string, unknown> = { name: error.name, message: error.message };
  if (error.stack) detail.stack = error.stack;
  const nodeError = error as Error & { code?: unknown; errno?: unknown; syscall?: unknown; hostname?: unknown; address?: unknown; port?: unknown; cause?: unknown };
  for (const key of ["code", "errno", "syscall", "hostname", "address", "port"] as const) {
    if (nodeError[key] !== undefined) detail[key] = nodeError[key];
  }
  if (nodeError.cause !== undefined && depth < 4) {
    detail.cause = nodeError.cause instanceof Error
      ? describeProxyError(nodeError.cause, depth + 1)
      : String(nodeError.cause);
  }
  return detail;
}

function safeEndpointForDiagnostics(endpoint: string): string {
  try {
    const url = new URL(endpoint);
    url.username = "";
    url.password = "";
    return url.toString();
  } catch {
    return endpoint;
  }
}

async function handlePost(request: Request) {
  logProxyCaller(request, "sparql.POST");
  let diagnosticEndpoint = "";
  let diagnosticOperation = "parse request";
  let diagnosticQuery = "";
  // Browser preferences are bounded and only control this request's execution time.
  const requestedMs = Number(request.headers.get("x-maestro-query-timeout-ms"));
  const queryTimeoutMs = Number.isInteger(requestedMs) && requestedMs >= 1000 && requestedMs <= 120000 ? requestedMs : undefined;
  try {
    const body = await request.json().catch(() => null);
    // Ordinary anonymous SPARQL execution only.
    const querySparql = (endpoint:string, query:string, timeout?:number,
      signal?:AbortSignal, priority?:QueryPriority, bypass=false, maxResponseBytes?:number) =>
      querySparqlTransport(endpoint,query,timeout,signal,priority,bypass,request,undefined,false,maxResponseBytes);
    // Connect's first request obtains the challenge only. The SPA sends the
    // same authenticated seed digest SELECT through the ordinary personal READ path.
    if (body?.operation === "auth-probe" && typeof body?.update !== "string") {
      const reply=(payload:unknown,status:number)=>NextResponse.json(payload,{status,headers:{"Cache-Control":"no-store"}});
      const identity=initialDigestIdentity(request);
      if(!identity)return reply({error:"Invalid personal Digest credentials."},400);
      const endpoint=digestEndpoint(identity);
      if(!permittedGraphServerTarget(endpoint) || typeof body.query!=="string" || !isBoundedReadOnlySparql(body.query,100000))
        return reply({error:"Expected a valid personal SELECT/ASK."},400);
      const first=await querySparqlTransport(endpoint,body.query.trim(),queryTimeoutMs,request.signal,undefined,true,request);
      if(first.response.status!==401)return reply({error:`Expected a Digest challenge; received HTTP ${first.response.status}.`},first.response.status>=400?first.response.status:502);
      const record=initialDigestRecord(identity,first.response.headers.get("www-authenticate"));
      if(!record)return reply({error:"Expected SPARQL realm, MD5 Digest and qop=auth."},401);
      // Return challenge metadata, not credentials, only to the same-origin caller.
      return reply({realm:record.realm,algorithm:record.algorithm,qop:record.qop,nonce:record.nonce,
        cnonce:record.cnonce,opaque:record.opaque,nc:record.nc},401);
    }
    // The same scoped Digest transport handles personal reads and writes.
    if (typeof body?.update === "string" && body?.personalWrite !== true)
      return NextResponse.json({error:"Authenticated personal SPARQL update required."},{status:401,headers:{"Cache-Control":"no-store"}});
    if(body?.personalRead===true || body?.personalWrite===true){
      const writing=body.personalWrite===true;
      const statement=writing?body.update:body.query;
      const address=typeof body.addr==="string"?body.addr:"";
      const at=address.lastIndexOf("@");
      const endpoint=at>=0?address.slice(at+1):"";
      if(!endpoint || !permittedGraphServerTarget(endpoint) || typeof statement!=="string" ||
        (writing ? body.query!==undefined || body.personalRead===true : body.update!==undefined || !isBoundedReadOnlySparql(statement,100000)))
        return NextResponse.json({error:"Expected a valid personal SPARQL operation."},{status:400,headers:{"Cache-Control":"no-store"}});
      if(writing){
        const record=restoredDigestRecord(request);
        if(!record || digestEndpoint(record)!==endpoint)return NextResponse.json({error:"No valid restored personal user session."},{status:401});
        const base=`${record.graphPrefix.replace(/\/+$/, "")}/query`;
        const graph=address.slice(0,at);
        const within=(iri:string)=>iri===base || iri.startsWith(`${base}/`) || iri.startsWith(`${base}#`);
        const update=statement.trim(), {graphs,hasImplicitGraph,clean,structure}=inspectPersonalUpdateGraphs(update);
        const max=/^INSERT\s+DATA\s*\{/i.test(update)?2_000_000:100_000;
        const load=/^LOAD\s+<([^<>]+)>\s+INTO\s+GRAPH\s+<([^<>]+)>$/i.exec(update);
        const safeLoad=Boolean(load && graphs.length===1 && graphs[0]===load[2] && load[1].length<=4096 && permittedGraphServerTarget(load[1]));
        const safeTemplates=hasExplicitPersonalUpdateTemplates(structure) && !/\\[uU]/.test(clean) &&
          !/\b(?:SERVICE|LOAD|CREATE|DROP|MOVE|COPY|ADD|WITH|USING|FROM|DEFINE|BASE)\b/i.test(clean) &&
          /^(?:INSERT|DELETE|CLEAR)\b/i.test(update) && !/\bCLEAR\s+(?:SILENT\s+)?(?:ALL|DEFAULT|NAMED)\b/i.test(clean);
        if(!within(graph) || !update || update.length>max || hasImplicitGraph || !graphs.length || !graphs.every(within) || !(safeTemplates || safeLoad))
          return NextResponse.json({error:"SPARQL Update requires explicit personal named graphs."},{status:400,headers:{"Cache-Control":"no-store"}});
        if(safeLoad && load)await checkGraphServerDestination(load[1]);
        if(graphs.includes(resolveGraph(GRAPH.STATUS,base)) && (typeof body.bookmarkQueryXml!=="string" || !body.bookmarkQueryXml))
          return NextResponse.json({error:"Bookmark the live FCT query before modifying Status."},{status:409,headers:{"Cache-Control":"no-store"}});
      }
      const authorization=restoredDigestAuthorization(request,endpoint);
      if(!authorization)return NextResponse.json({error:"No valid restored personal user session."},{status:401,headers:{"Cache-Control":"no-store"}});
      let {response,responseText}=await querySparqlTransport(endpoint,statement.trim(),queryTimeoutMs,request.signal,undefined,true,request,authorization,writing);
      const headers:Record<string,string>={"Cache-Control":"no-store"};
      if(response.status===401){
        const renewed=staleDigestRecord(request,endpoint,response.headers.get("www-authenticate"));
        const retry=renewed&&digestRecordAuthorization(renewed,endpoint);
        if(renewed && retry){
          ({response,responseText}=await querySparqlTransport(endpoint,statement.trim(),queryTimeoutMs,request.signal,undefined,true,request,retry,writing));
          if(response.ok)headers["x-maestro-digest-refresh"]=encodeURIComponent(JSON.stringify({realm:renewed.realm,algorithm:renewed.algorithm,qop:renewed.qop,nonce:renewed.nonce,cnonce:renewed.cnonce,opaque:renewed.opaque,nc:renewed.nc}));
        }
      }
      Object.assign(headers, upstreamDiagnosticHeaders(response));
      const incomplete=response.status===206 || isVirtuosoAnytime(response,responseText);
      if(!response.ok&&!incomplete)return NextResponse.json({error:`Personal SPARQL HTTP ${response.status}${responseText.trim()?`: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}`:""}`},{status:response.status>=400?response.status:502,headers});
      if(incomplete)Object.assign(headers,anytimeResponseHeaders(response,true));
      if(incomplete&&writing)return NextResponse.json({error:"Incomplete personal SPARQL update.",incomplete:true},{status:502,headers});
      if(writing)return new Response(null,{status:204,headers});
      if(/^\s*(?:(?:PREFIX\s+[^\n]+)\s*)?ASK\b/i.test(body.query.trim())) {
        try { const result=JSON.parse(responseText); if(typeof result.boolean==="boolean")return NextResponse.json({...result,incomplete},{headers}); } catch {}
      }
      const parsed=parseSparqlResults(responseText);
      if(!parsed)return NextResponse.json({error:incomplete?"Incomplete personal SPARQL result with no usable bindings.":"Invalid personal SPARQL results.",incomplete},{status:502,headers});
      return NextResponse.json({...parsed,incomplete},{headers});
    }
    // Every SPARQL request carries the address of its originating FCT query.
    const nested = body?.recordSelect ?? body?.recordValueLabels ?? body?.facetValueCount;
    const explicitAddr = (typeof nested?.addr === "string" ? nested.addr : "") ||
      (typeof body?.addr === "string" ? body.addr : "") ||
      fctAddrFromXml(nested?.queryXml ?? body?.queryXml);
    const selectedEndpoint = resolveFctEndpointFromAddr([], explicitAddr);
    const fctEndpoint = selectedEndpoint?.url;
    diagnosticEndpoint = fctEndpoint ?? "";
    if (!fctEndpoint) {
      return NextResponse.json({ error: "SPARQL operation requires a valid graph server in query addr." }, { status: 400 });
    }

    // Generic read-only SPARQL transport. Used for diagnostics that cannot be
    // represented by an RDF property (e.g. Virtuoso sys_stat) and graph-server
    // service-description metadata. No feature-specific JSON API is needed.
    if (typeof body?.query === "string") {
      const query = body.query.trim();
      const maximumQueryLength = 100000;
      if (query.length > maximumQueryLength) {
        return NextResponse.json({ error: `Read-only SPARQL query exceeds the ${maximumQueryLength}-character gateway limit (${query.length} characters).` }, { status: 413 });
      }
      if (!isBoundedReadOnlySparql(query, maximumQueryLength)) {
        return NextResponse.json({ error: "Expected a bounded read-only SELECT/ASK query" }, { status: 400 });
      }
      // Scheduler-only priority hint, not a Maestro domain query operation.
      // An untrusted client cannot mark an arbitrary expensive SELECT as urgent.
      const autocomplete = body?.requestClass === "autocomplete";
      // Request-scoped RDF identities must not enter shared response caches.
      // The caller owns parsing and domain semantics.
      const requestScoped = body?.responseScope === "request";
      // Generic request-scoped transport budget supplied by the browser. No
      // Maestro feature defaults or domain policy belong in this proxy.
      const maxResponseBytes = requestScoped ? body.maxResponseBytes : undefined;
      if (requestScoped && (typeof maxResponseBytes !== "number" || !Number.isSafeInteger(maxResponseBytes) || maxResponseBytes < 1)) {
        return NextResponse.json({ error: "Request-scoped SPARQL requires a positive integer maxResponseBytes." }, { status: 400 });
      }
      // A priority autocomplete request is a bounded ranked *resource* lookup.
      // The single-query form now enriches only the inner top N URIs with
      // OPTIONAL rdf:type and removes asserted superclasses. Do not reject
      // legitimate GROUP BY / OPTIONAL merely because class metadata is in the
      // same request, and do not promote arbitrary read-only SPARQL to priority.
      const candidateLimits = [...query.matchAll(/\bLIMIT\s+(\d+)\b/gi)].map(match => Number(match[1]));
      const mergedRankedAutocomplete = /^SELECT\s+\?uri\s+\?label\s+\?type\s+WHERE\s*\{\s*\{\s*SELECT\s+\?uri\s+\(SAMPLE\(\?matchedLabel\)\s+AS\s+\?label\)/i.test(query) &&
        /GROUP\s+BY\s+\?uri\s+ORDER\s+BY\s+DESC\s*\(\s*<LONG::IRI_RANK>\s*\(\?uri\)\s*\)/i.test(query) &&
        /\?matchedLabel\s+bif:contains\s+/i.test(query) &&
        /FILTER\(LCASE\(STR\(\?matchedLabel\)\)\s*=\s*/i.test(query) &&
        /OPTIONAL\s*\{[\s\S]*\?uri\s+<http:\/\/www\.w3\.org\/1999\/02\/22-rdf-syntax-ns#type>\s+\?type/i.test(query) &&
        /FILTER\s+NOT\s+EXISTS\s*\{/i.test(query) &&
        /<http:\/\/www\.w3\.org\/2000\/01\/rdf-schema#subClassOf>\+\s+\?type/i.test(query) &&
        /ORDER\s+BY\s+DESC\s*\(\s*<LONG::IRI_RANK>\s*\(\?uri\)\s*\)[\s\S]*$/.test(query);
      if (autocomplete && (query.length > 4000 || !mergedRankedAutocomplete ||
          candidateLimits.length !== 1 || candidateLimits[0] < 1 || candidateLimits[0] > 10 ||
          /\b(?:SERVICE|UNION|VALUES|CONSTRUCT|DESCRIBE|INSERT|DELETE|LOAD|CLEAR|DROP|CREATE)\b/i.test(query))) {
        return NextResponse.json({error:"Autocomplete priority requires an indexed, ranked, bounded URI lookup with optional class enrichment."},{status:400});
      }
      diagnosticOperation = autocomplete ? "priority URI autocomplete" : "generic read-only SPARQL";
      diagnosticQuery = query;
      const { responseText, response, key } = await querySparql(fctEndpoint, query, autocomplete ? Math.min(120000, Math.max(1000, queryTimeoutMs || 5000)) : queryTimeoutMs, request.signal, autocomplete ? "autocomplete" : undefined, requestScoped || request.headers.get("x-maestro-component-retry") === "1", maxResponseBytes);
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      const headers = { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) };
      if (!response.ok && !incomplete) return NextResponse.json({ error: `SPARQL HTTP ${response.status}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity), ...(response.headers.get("X-Maestro-Response-Limit") === "exceeded" ? { code: "RESPONSE_LIMIT_EXCEEDED" } : {}) }, { status: response.status, headers });
      if (requestScoped) {
        // No parse/re-encode or persistence of response-local identities.
        return new Response(responseText, { status: 200, headers: { ...headers, "Content-Type": "application/sparql-results+json; charset=utf-8" } });
      }
      let parsed: ReturnType<typeof parseSparqlResults> | { boolean: boolean } = parseSparqlResults(responseText);
      // Generic ASK is a legitimate SPARQL Results JSON document too.
      if (!parsed) {
        try { const value = JSON.parse(responseText); if (typeof value.boolean === "boolean") parsed = { boolean: value.boolean }; } catch { /* invalid result */ }
      }
      if (!parsed) return NextResponse.json({ error: "No usable SPARQL result document was delivered." }, { status: 502, headers: { ...upstreamDiagnosticHeaders(response), "Cache-Control": "no-store" } });
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, incomplete }, { headers });
    }

    // Resolve still-missing URI labels only in named graphs that the existing
    // Record graph dropdown has already discovered. This is a separate, bounded
    // operation: the initial Record SELECT never waits for graph enumeration.
    if (body?.recordValueLabels && typeof body.recordValueLabels === "object") {
      const { uris, graphs, preferredLanguage } = body.recordValueLabels as { uris?: unknown; graphs?: unknown; preferredLanguage?: unknown };
      const resources = uniqueIris(uris, 128);
      const namedGraphs = uniqueIris(graphs, 500);
      if (!resources || !namedGraphs || resources.length === 0 ||
          typeof preferredLanguage !== "string" || (preferredLanguage !== "all" && !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(preferredLanguage))) {
        return NextResponse.json({ error: "Record label enrichment requires URI values and a valid language." }, { status: 400 });
      }
      // EURIO v2.4 object-property ranges, used only for already selected
      // Record-linked URIs: Project -> Grant -> FundingScheme (including the
      // Programme/Call subproperties), Project -> Role -> Organisation/Person,
      // and Project -> EuroSciVoc Concept -> SKOS-XL Label. Each hop can live
      // in a DIFFERENT named graph: do not bind all hops to one ?labelGraph.
      // Explicit Record graph selections remain confined to their graphs.
      const graphScope = (variable: string) => namedGraphs.length
        ? `VALUES ?${variable} { ${iriList(namedGraphs)} }` : "";
      const directLabels = `
        <http://www.w3.org/2000/01/rdf-schema#label>
        <http://www.w3.org/2004/02/skos/core#prefLabel>
        <http://schema.org/name>
        <https://schema.org/name>
        <http://xmlns.com/foaf/0.1/name>
        <http://purl.org/dc/terms/title>
        <http://www.w3.org/2004/02/skos/core#notation>
        <http://data.europa.eu/s66#title>
        <http://data.europa.eu/s66#name>
        <http://data.europa.eu/s66#legalName>
        <http://data.europa.eu/s66#roleLabel>
        <http://data.europa.eu/s66#code>
        <http://data.europa.eu/s66#definition>`;
      const query = `SELECT DISTINCT ?labelResource ?labelPredicate ?label WHERE {
        VALUES ?labelResource { ${iriList(resources)} }
        {
          # Direct names: Project, Result, Grant, FundingScheme, Organisation,
          # Role and Acronym all use the properties above as appropriate.
          ${graphScope("directGraph")}
          GRAPH ?directGraph {
            VALUES ?labelPredicate { ${directLabels} }
            ?labelResource ?labelPredicate ?label .
          }
        }
        UNION
        {
          # EuroSciVoc, FundingScheme categories and other SKOS-XL concepts.
          ${graphScope("conceptGraph")}
          GRAPH ?conceptGraph {
            ?labelResource <http://www.w3.org/2008/05/skos-xl#prefLabel> ?xlLabel .
          }
          ${graphScope("xlGraph")}
          GRAPH ?xlGraph { ?xlLabel <http://www.w3.org/2008/05/skos-xl#literalForm> ?label . }
          BIND(<http://www.w3.org/2008/05/skos-xl#prefLabel> AS ?labelPredicate)
        }
        UNION
        {
          # The ontology declares both Programme and Call as subproperties of
          # hasFundingScheme. CORDIS may assert only the specific predicates.
          VALUES ?schemeLink {
            <http://data.europa.eu/s66#hasFundingScheme>
            <http://data.europa.eu/s66#hasFundingSchemeProgramme>
            <http://data.europa.eu/s66#hasFundingSchemeCall>
            <http://data.europa.eu/s66#hasAssociatedFundingScheme>
          }
          ${graphScope("grantGraph")}
          GRAPH ?grantGraph { ?labelResource ?schemeLink ?scheme . }
          ${graphScope("schemeGraph")}
          GRAPH ?schemeGraph {
            VALUES ?schemePredicate { ${directLabels} }
            ?scheme ?schemePredicate ?label .
          }
          BIND(?schemeLink AS ?labelPredicate)
        }
        UNION
        {
          # A Role does not always have its own label. Its real participant
          # name is on the connected Organisation/Person (eurio:legalName etc).
          ${graphScope("roleGraph")}
          GRAPH ?roleGraph {
            ?labelResource <http://data.europa.eu/s66#isRoleOf> ?actor .
          }
          ${graphScope("actorGraph")}
          GRAPH ?actorGraph {
            VALUES ?actorNamePredicate { ${directLabels} }
            ?actor ?actorNamePredicate ?label .
          }
          BIND(<http://data.europa.eu/s66#isRoleOf> AS ?labelPredicate)
        }
        UNION
        {
          # Funding schemes sometimes have only a coded classification.
          ${graphScope("categorySchemeGraph")}
          GRAPH ?categorySchemeGraph {
            ?labelResource <http://data.europa.eu/s66#hasFundingSchemeCategory> ?category .
          }
          ${graphScope("categoryGraph")}
          GRAPH ?categoryGraph {
            ?category <http://www.w3.org/2008/05/skos-xl#prefLabel> ?categoryLabel .
          }
          ${graphScope("categoryLabelGraph")}
          GRAPH ?categoryLabelGraph {
            ?categoryLabel <http://www.w3.org/2008/05/skos-xl#literalForm> ?label .
          }
          BIND(<http://data.europa.eu/s66#hasFundingSchemeCategory> AS ?labelPredicate)
        }
        FILTER(isLiteral(?label) && (${preferredLanguage === "all" ? "true" : `DATATYPE(?label) != <http://www.w3.org/1999/02/22-rdf-syntax-ns#langString> || LANGMATCHES(LANG(?label), ${JSON.stringify(preferredLanguage)})`}))
      } LIMIT 4096`;
      diagnosticOperation = "Record URI labels (including nested SKOS-XL)";
      diagnosticQuery = query;
      // A user may open a blank-node Record from a ranked FCT Results page.
      // The Results SELECT is nested in this Record query; on Virtuoso instances
      // without the Facet VAD, retry without ONLY the generated IRI_RANK sort.
      let recordQuery = query;
      let recordResult = await querySparql(fctEndpoint, recordQuery, queryTimeoutMs, request.signal);
      if (!recordResult.response.ok && recordResult.response.status !== 206 &&
          !isVirtuosoAnytime(recordResult.response, recordResult.responseText)) {
        const fallback = unorderedIriRankFallback(recordQuery, recordResult.responseText + " " +
          (recordResult.response.headers.get("X-SQL-Message") ?? ""));
        if (fallback) {
          recordQuery = fallback;
          recordResult = await querySparql(fctEndpoint, recordQuery, queryTimeoutMs, request.signal);
          diagnosticQuery = recordQuery;
        }
      }
      const { responseText, response, key } = recordResult;
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (!response.ok && !incomplete) {
        return NextResponse.json({ error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` }, { status: response.status, headers: upstreamDiagnosticHeaders(response) });
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed) return NextResponse.json({ error: "Invalid Record label SELECT results JSON." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, incomplete, query }, {
        headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
      });
    }

    // One authoritative, language-filtered Record snapshot. This query does not
    // join labels: URI display names are enriched asynchronously and are not
    // Record triples. Filter inside WHERE, BEFORE LIMIT, so the limit counts
    // eligible triples rather than multilingual values that will be discarded.
    if (body?.recordSelect && typeof body.recordSelect === "object") {
      const { iri, termType = "uri", datatype, lang, limit, graphs, focusPredicate, preferredLanguage, queryXml } = body.recordSelect as RecordSelectTerm & { limit?: unknown; graphs?: unknown; focusPredicate?: unknown; preferredLanguage?: unknown; queryXml?: unknown };
      // The Record uses the graph server in the originating FCT query.
      let recordEndpoint = fctEndpoint;
      if (typeof queryXml === "string" && queryXml.trim()) {
        const rootTag = queryXml.match(/<query\b([^>]*)>/i)?.[1] ?? "";
        const addr = rootTag.match(/\baddr\s*=\s*(["'])(.*?)\1/i)?.[2]?.replace(/&amp;/g, "&") ?? "";
        const delimiter = addr.indexOf("@");
        const server = delimiter >= 0 ? normalizeGraphServerUri(addr.slice(delimiter + 1).trim()) : "";
        if (!server) return NextResponse.json({ error: "Record query has no graph server in addr." }, { status: 400 });
        if (!permittedGraphServerTarget(server))
          return NextResponse.json({ error: `Invalid or unsafe Record graph server: ${server}` }, { status: 400 });
        recordEndpoint = server;
      }
      diagnosticEndpoint = recordEndpoint;
      const namedGraphs = graphs === undefined ? [] : uniqueIris(graphs, 500);
      const record = safeRecordSelectTerm({ iri, termType, datatype, lang });
      if (!record || !Number.isInteger(limit) || typeof limit !== "number" || limit < 1 || limit > 10000 || !namedGraphs ||
          (focusPredicate !== undefined && !isSafeIri(focusPredicate)) ||
          (typeof preferredLanguage !== "string" || (preferredLanguage !== "all" && !/^[A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(preferredLanguage)))) {
        return NextResponse.json({ error: "A valid Record RDF term, preferred language, limit (1–10000), and optional graph IRI list are required." }, { status: 400 });
      }
      const graphPrefix = namedGraphs.length ? `VALUES ?recordGraph { ${iriList(namedGraphs)} } GRAPH ?recordGraph { ` : "";
      const graphSuffix = namedGraphs.length ? " }" : "";
      // JSON.stringify escapes the validated BCP-47 language for SPARQL.
      const allowedLiteral = `FILTER(${preferredLanguage === "all" ? "true" : `!isLiteral(?object) || DATATYPE(?object) != <http://www.w3.org/1999/02/22-rdf-syntax-ns#langString> || LANGMATCHES(LANG(?object), ${JSON.stringify(preferredLanguage)})`})`;
      // Literal focus nodes have only incoming roles. The object is the focus
      // literal itself, so no language filtering is applied to the focus term.
      let query = termType === "literal"
        ? `SELECT ?subject ?predicate ?object WHERE {
             { SELECT ?subject ?predicate WHERE {
                 ${graphPrefix}?subject ?predicate ${record} .${graphSuffix}
               } LIMIT ${limit} }
             BIND(${record} AS ?object)
           }`
        : `SELECT ?subject ?predicate ?object WHERE {
             ${graphPrefix}
               { ${record} ?predicate ?object . BIND(${record} AS ?subject) }
               UNION { ?subject ?predicate ${record} . BIND(${record} AS ?object) }
             ${graphSuffix}
             ${allowedLiteral}
           } LIMIT ${limit}`;
      diagnosticOperation = termType === "literal" ? "Literal Record incoming Roles" : "Language-filtered Record SELECT";
      diagnosticQuery = query;
      let result: SparqlQueryResult;
      let focusedFallback = false;
      try {
        // Don't make the user wait a full 20 seconds for a global Roles scan
        // when the focus property already establishes a useful incoming role.
        const scanTimeout = termType === "literal" && focusPredicate
          ? Math.min(queryTimeoutMs ?? 20000, 5000) : queryTimeoutMs;
        result = await querySparql(recordEndpoint, query, scanTimeout, request.signal, undefined, request.headers.get("x-maestro-component-retry") === "1");
      } catch (error) {
        if (termType !== "literal" || !focusPredicate ||
            !/timeout|abort|UND_ERR_CONNECT_TIMEOUT/i.test(String(error instanceof Error ? error.message + " " + String(error.cause) : error))) throw error;
        focusedFallback = true;
        query = `SELECT ?subject ?predicate ?object WHERE {
          { SELECT ?subject WHERE {
            ${graphPrefix}?subject <${focusPredicate}> ${record} .${graphSuffix}
          } LIMIT ${limit} }
          BIND(<${focusPredicate}> AS ?predicate)
          BIND(${record} AS ?object)
        }`;
        diagnosticQuery = query;
        result = await querySparql(recordEndpoint, query, queryTimeoutMs, request.signal, undefined, request.headers.get("x-maestro-component-retry") === "1");
      }
      const { responseText, response, key } = result;
      const incomplete = focusedFallback || response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (!response.ok && !incomplete) {
        return NextResponse.json({ error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` }, { status: response.status, headers: upstreamDiagnosticHeaders(response) });
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed) return NextResponse.json({ error: "No usable Record SELECT result document was delivered." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      if (parsed && !["subject", "predicate", "object"].every((name) => parsed.head.vars.includes(name))) {
        return NextResponse.json({ error: "Record SELECT response lacks RDF triple columns." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete && parsed) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, incomplete, query }, {
        headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
      });
    }

    // The Results pane compiles the authoritative FCT query tree to SPARQL on
    // the client and submits that SELECT here; unlike /fct, this path returns
    // the endpoint's SPARQL result bindings directly.
    if (body?.resultsQuery && typeof body.resultsQuery === "object") {
      const resultsQuery = body.resultsQuery.sparql;
      const selectSyntax = typeof resultsQuery === "string"
        ? resultsQuery.replace(/<[^>]*>|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g, " ") : "";
      if (typeof resultsQuery !== "string" || !/^\s*(?:DEFINE\s+[^\n]+\s+)*SELECT\b/i.test(resultsQuery) ||
          !/\bAS\s+\?c1\b/i.test(resultsQuery) || /\b(?:INSERT|DELETE|CLEAR|LOAD|CREATE|DROP|MOVE|COPY|ADD)\b/i.test(selectSyntax)) {
        return NextResponse.json({ error: "A client-generated SELECT Results SPARQL query with ?c1 is required." }, { status: 400 });
      }
      diagnosticOperation = "Results SPARQL query";
      diagnosticQuery = resultsQuery;
      let actualQuery = resultsQuery;
      // A user-initiated component retry must not replay the proxy's previous
      // Results snapshot. It is still the same read-only cloned query, not a
      // Browse query mutation or new transport endpoint.
      const bypassComponentCache = request.headers.get("x-maestro-component-retry") === "1";
      let queryResult = await querySparql(fctEndpoint, actualQuery, queryTimeoutMs, request.signal, undefined, bypassComponentCache);
      if (!queryResult.response.ok && queryResult.response.status !== 206 &&
          !isVirtuosoAnytime(queryResult.response, queryResult.responseText)) {
        const fallback = unorderedIriRankFallback(resultsQuery, queryResult.responseText + " " +
          (queryResult.response.headers.get("X-SQL-Message") ?? ""));
        if (fallback) {
          actualQuery = fallback;
          queryResult = await querySparql(fctEndpoint, fallback, queryTimeoutMs, request.signal, undefined, bypassComponentCache);
        }
      }
      const { responseText, response, key } = queryResult;
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText);
      if (!parsed || !parsed.head.vars.includes("c1")) {
        return NextResponse.json({ error: "Virtuoso returned invalid Results SPARQL JSON (expected ?c1)." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, query: actualQuery, incomplete,
        orderingFallback: actualQuery !== resultsQuery }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    if (body?.facetValueCount && typeof body.facetValueCount === "object") {
      const sourceQuery = body.facetValueCount.sparql;
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The client-generated scalar count SPARQL query is required." }, { status: 400 });
      }
      const numericDomain = body.facetValueCount.numericDomain === true;
      const temporalDomain = body.facetValueCount.temporalDomain === true;
      if (numericDomain && temporalDomain) return NextResponse.json({ error: "Conflicting facet domain types." }, { status: 400 });
      const countQuery = validateFacetValueCountQuery(sourceQuery, numericDomain, temporalDomain);
      if (!countQuery) {
        return NextResponse.json({ error: numericDomain
          ? "Numeric facet requires COUNT(?ct), MIN(?facetNumber) and MAX(?facetNumber) projections."
          : temporalDomain ? "Temporal facet requires COUNT(?ct), MIN(?facetLex) and MAX(?facetLex) projections."
          : "The client must provide a scalar COUNT(...) AS ?ct SPARQL query." }, { status: 400 });
      }

      // Count against the graph server named by the FCT query, not the shared
      // selection state (which can lag query restoration or server changes).
      const address = body.facetValueCount.addr;
      if (typeof address !== "string" || !address.includes("@")) {
        return NextResponse.json({ error: "Facet count requires the FCT query address." }, { status: 400 });
      }
      const serverUri = normalizeGraphServerUri(address.slice(address.indexOf("@") + 1));
      if (!permittedGraphServerTarget(serverUri)) {
        return NextResponse.json({ error: "Invalid or unsafe facet count graph server." }, { status: 400 });
      }
      diagnosticOperation = "facet value count SPARQL query";
      diagnosticQuery = countQuery;
      diagnosticEndpoint = serverUri;
      const { responseText, response, key } = await querySparql(serverUri, countQuery, queryTimeoutMs, request.signal);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText);
      if (!parsed) return NextResponse.json({ error: "No usable SPARQL count result document was delivered." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      const countValue = parsed?.results.bindings[0]?.ct?.value;
      const count = countValue !== undefined && /^\d+$/.test(countValue) ? Number(countValue) : NaN;
      if (!parsed || !parsed.head.vars.includes("ct") || parsed.results.bindings.length !== 1 ||
          !Number.isSafeInteger(count) || count < 0) {
        if (incomplete) return NextResponse.json({ incomplete: true, query: countQuery }, { headers: sparqlResponseHeaders(response, true) });
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL count result." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      if (numericDomain || temporalDomain) {
        const row = parsed.results.bindings[0];
        const min = row?.min?.value ?? null;
        const max = row?.max?.value ?? null;
        if (!parsed.head.vars.includes("min") || !parsed.head.vars.includes("max"))
          return NextResponse.json({ error: "Virtuoso omitted facet domain projections." }, { status: 502 });
        return NextResponse.json({ count, min, max, query: countQuery, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
      }
      return NextResponse.json({ count, query: countQuery, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    if (body?.facetIntersection && typeof body.facetIntersection === "object") {
      const sourceQuery = body.facetIntersection.sparql;
      const candidates = uniqueIris(body.facetIntersection.candidates, 500);
      if (!candidates) {
        return NextResponse.json({ error: "Autoconfigure candidates must be valid IRIs (maximum 500)." }, { status: 400 });
      }
      if (!candidates.length) return NextResponse.json({ uris: [] });
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The generated facet SPARQL query is required." }, { status: 400 });
      }
      const built = buildFacetIntersectionQuery(sourceQuery, candidates);
      if (!built) {
        return NextResponse.json({ error: "Could not safely add the high-frequency facets to the generated SPARQL query." }, { status: 400 });
      }

      diagnosticOperation = "facet intersection SPARQL query";
      diagnosticQuery = built.query;
      const { responseText, response, key } = await querySparql(fctEndpoint, built.query, queryTimeoutMs, request.signal);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
          { status: response.status, headers: upstreamDiagnosticHeaders(response) },
        );
      }
      const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
      if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
      const parsed = parseSparqlResults(responseText);
      if (!parsed || !parsed.head.vars.includes(built.variable)) {
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL facet-intersection result." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
      }
      const bindings = parsed.results.bindings;
      const uris = [...new Set(bindings
        .map((binding) => binding[built.variable]?.value)
        .filter((value): value is string => typeof value === "string" && value.length > 0))];
      if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
      return NextResponse.json({ uris, incomplete }, { headers: sparqlResponseHeaders(response, incomplete) });
    }

    // Results enrichment is intentionally bounded to exact FCT result URIs and
    // the selected relationships, rather than accepting arbitrary SPARQL.
    const resources = uniqueIris(body?.resources, 100);
    const properties = uniqueIris(body?.properties ?? [], 100);
    const roles = uniqueIris(body?.roles ?? [], 100);
    if (!resources || resources.length === 0) {
      return NextResponse.json({ error: "One or more valid FCT result resource URIs are required." }, { status: 400 });
    }
    if (!properties || !roles) {
      return NextResponse.json({ error: "Selected property and role lists must contain valid IRIs (maximum 100 each)." }, { status: 400 });
    }
    if (properties.length + roles.length === 0) {
      return NextResponse.json({ head: { vars: [] }, results: { bindings: [] } });
    }

    const resourceValues = iriList(resources);
    const branches: string[] = [];
    if (properties.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(properties)} } ?resource ?property ?value . BIND("forward" AS ?direction) }`);
    }
    if (roles.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(roles)} } ?value ?property ?resource . BIND("reverse" AS ?direction) }`);
    }
    const query = `SELECT DISTINCT ?resource ?property ?direction ?value WHERE { ${branches.join(" UNION ")} }`;
    diagnosticOperation = "result relationship enrichment SPARQL query";
    diagnosticQuery = query;
    const { responseText, response, key } = await querySparql(fctEndpoint, query, queryTimeoutMs, request.signal);
    const contentType = response.headers.get("content-type") ?? "";
    if (!response.ok && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
      proxyLog("error", "sparql.upstream-http", { operation: diagnosticOperation, status: response.status, responseBody: responseText });
      return NextResponse.json(
        { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
        { status: response.status, headers: upstreamDiagnosticHeaders(response) },
      );
    }
    if (!contentType.toLowerCase().includes("json") && !(response.status === 206 || isVirtuosoAnytime(response, responseText))) {
      return NextResponse.json(
        { error: `Virtuoso SPARQL endpoint did not return JSON results${responseText.trim() ? `: ${sanitizeUpstreamDiagnostic(responseText.trim(), Infinity)}` : "."}`, details: sanitizeUpstreamDiagnostic(responseText, Infinity) },
        { status: response.status, headers: upstreamDiagnosticHeaders(response) },
      );
    }

    const incomplete = response.status === 206 || isVirtuosoAnytime(response, responseText);
    if (incomplete) proxyLog("warn", "sparql.anytime", { operation: diagnosticOperation, message: virtuosoAnytimeMessage(response, responseText) });
    const parsed = parseSparqlResults(responseText);
    if (!parsed) {
      return NextResponse.json({ error: "No usable SPARQL result document was delivered." }, { status: 502, headers: upstreamDiagnosticHeaders(response) });
    }
    if (response.status === 200 && !incomplete) setQueryCache(key, responseText);
    return NextResponse.json({ ...parsed, incomplete }, {
      status: 200,
      headers: { "Cache-Control": "no-store", ...sparqlResponseHeaders(response, incomplete) },
    });
  } catch (error) {
    const diagnostics = {
      route: "sparql.POST",
      operation: diagnosticOperation,
      endpoint: diagnosticEndpoint ? safeEndpointForDiagnostics(diagnosticEndpoint) : null,
      query: diagnosticQuery || null,
      error: describeProxyError(error),
    };
    // proxyFailure records expected deadlines at debug level. Do not duplicate
    // a full stack/error payload for timeout or intentionally cancelled work.
    if (!request.signal.aborted && !/timed? out|aborted due to timeout/i.test(describeUpstreamError(error))) {
      proxyLog("error", "sparql.POST.failed", { operation: diagnosticOperation, endpoint: diagnostics.endpoint, error: diagnostics.error, err: error });
    }
    return proxyFailure(request, "sparql.POST", error, { operation: diagnosticOperation, endpoint: diagnostics.endpoint });
  }
}

export async function POST(request: Request): Promise<Response> {
  // Leave SPARQL's native response untouched; push telemetry on /events.
  return withProxyQueryTelemetry(request,
    () => withProxyClient(request, () => handlePost(request)));
}
