import { logProxyCaller } from "@/lib/proxy-debug";
import { NextResponse } from "next/server";
import { getQueryCache, queryCacheKey, setQueryCache } from "@/lib/query-cache";

type FctEndpoint = { id: string; label: string; url: string; group: string };

function slugify(value: string) {
  return value.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function getConfiguredEndpoints(): FctEndpoint[] {
  const configured = (process.env.FCT_ENDPOINTS ?? "")
    .split(";")
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const separator = entry.indexOf("=");
      if (separator <= 0) return null;
      const left = entry.slice(0, separator).trim();
      const rawUrl = entry.slice(separator + 1).trim();
      if (!left || !/^https?:\/\//i.test(rawUrl)) return null;
      const groupSeparator = left.indexOf("::");
      const group = groupSeparator >= 0 ? left.slice(0, groupSeparator).trim() : "Endpoints";
      const label = (groupSeparator >= 0 ? left.slice(groupSeparator + 2) : left).trim();
      if (!label) return null;

      return {
        id: groupSeparator >= 0 ? slugify(`${group}-${label}`) : slugify(label),
        group: group || "Endpoints",
        label,
        url: rawUrl,
      };
    })
    .filter((endpoint): endpoint is FctEndpoint => Boolean(endpoint));

  const legacyUrl = (process.env.FCT_ENDPOINT ?? "").trim();
  if (legacyUrl && !configured.some((endpoint) => endpoint.url === legacyUrl)) {
    configured.unshift({ id: slugify("Current VOS"), group: "Endpoints", label: "Current VOS", url: legacyUrl });
  }

  const seen = new Set<string>();
  return configured.filter((endpoint) => {
    if (seen.has(endpoint.id)) return false;
    seen.add(endpoint.id);
    return true;
  });
}

function getSelectedEndpointId(request: Request, endpoints: FctEndpoint[]) {
  const cookie = request.headers.get("cookie") ?? "";
  const match = cookie.match(/(?:^|;\s*)fct_endpoint=([^;]+)/);
  const id = match ? decodeURIComponent(match[1]) : "";
  return endpoints.some((endpoint) => endpoint.id === id) ? id : endpoints[0]?.id ?? "";
}

function isSafeIri(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= 4096 &&
    !/[<>"{}|^`\\\u0000-\u0020]/.test(value);
}

function uniqueIris(value: unknown, max: number): string[] | null {
  if (!Array.isArray(value) || value.length > max || !value.every(isSafeIri)) return null;
  return [...new Set(value)];
}

function iriList(values: string[]): string {
  return values.map((value) => `<${value}>`).join(" ");
}

function buildFacetIntersectionQuery(sourceQuery: string, candidates: string[]): { query: string; variable: string } | null {
  const sparql = decodeSparqlHtmlEntities(sourceQuery).trim();
  if (!sparql || sparql.length > 100_000 || !/\bSELECT\b/i.test(sparql)) return null;
  // This route only accepts the read-only SELECT generated by the FCT facet widget.
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH)\b/i.test(sparql)) return null;

  const selectMatch = sparql.match(/\bSELECT\s+(?:(?:DISTINCT|REDUCED)\s+)?([\s\S]*?)(?:\bWHERE\s*)?\{/i);
  if (!selectMatch) return null;
  const variableMatch = selectMatch[1].match(/\?([A-Za-z_][A-Za-z0-9_]*)/);
  if (!variableMatch) return null;
  const variable = variableMatch[1];

  // Insert a VALUES restriction into the original query's outer WHERE group. This
  // preserves the generated query's graph patterns and computes the actual set
  // intersection at the SPARQL endpoint, rather than intersecting in the browser.
  const selectEnd = selectMatch.index ?? 0;
  const whereMatch = /\bWHERE\s*\{/ig;
  whereMatch.lastIndex = selectEnd;
  const explicitWhere = whereMatch.exec(sparql);
  let openBrace = -1;
  if (explicitWhere) {
    openBrace = explicitWhere.index + explicitWhere[0].lastIndexOf("{");
  } else {
    const brace = sparql.indexOf("{", selectEnd);
    openBrace = brace;
  }
  if (openBrace < 0) return null;

  const values = `\n  VALUES ?${variable} { ${iriList(candidates)} }\n`;
  return {
    query: `${sparql.slice(0, openBrace + 1)}${values}${sparql.slice(openBrace + 1)}`,
    variable,
  };
}

/**
 * Build a temporary aggregate query from the scope-correct SPARQL generated by
 * the FCT text view. FCT's generated SELECT projects the current result resource
 * first (normally ?s1); counting distinct values of that variable gives the
 * number of resources matching the current Properties/Roles scope.
 *
 * This is intentionally a narrow translator for read-only FCT-generated SELECT
 * queries, not a general SPARQL query rewriter. Native FCT list-count should
 * replace this workaround once the local /sparql endpoint is fixed.
 */
function decodeSparqlHtmlEntities(sourceQuery: string): string {
  return sourceQuery
    .replace(/&#39;|&#x27;/gi, "'")
    .replace(/&quot;/gi, '"')
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&amp;/gi, "&");
}

function validateFacetValueCountQuery(query: string): string | null {
  const sparseQuery = query.trim();
  if (!sparseQuery || sparseQuery.length > 100_000) return null;

  // FCT-generated Virtuoso queries may start with BASE, PREFIX, and/or DEFINE
  // prologue declarations. Validate the SELECT shape after those declarations,
  // but forward the original query unchanged so graph settings and prefixes
  // are preserved at the endpoint.
  let selectQuery = sparseQuery;
  while (true) {
    selectQuery = selectQuery.trimStart();
    const prologue = selectQuery.match(
      /^(?:BASE\s+<[^>]*>|PREFIX\s+(?:[A-Za-z_][A-Za-z0-9_-]*)?:\s*<[^>]*>|DEFINE\s+[A-Za-z_][A-Za-z0-9_-]*:[A-Za-z_][A-Za-z0-9_-]*\s+(?:<[^>]*>|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[^\s]+))\s*/i,
    );
    if (!prologue) break;
    selectQuery = selectQuery.slice(prologue[0].length);
  }

  // The client owns query construction. The proxy accepts only the scalar
  // COUNT query shape for this operation and forwards it unchanged.
  if (!/^SELECT\s*\(\s*COUNT\s*\(\s*(?:DISTINCT\s+\?[A-Za-z_][A-Za-z0-9_]*|\*)\s*\)\s+AS\s+\?ct\s*\)\s+WHERE\s*\{/i.test(selectQuery)) return null;
  // Ignore operation-looking words inside RDF IRIs, string literals, and
  // comments. Count text searches may legitimately contain terms such as
  // "with", "delete", or "create"; they are not SPARQL update operations.
  const syntaxOnly = sparseQuery.replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|<[^>]*>|#[^\r\n]*/g, " ");
  if (/\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH|UPDATE)\b/i.test(syntaxOnly)) return null;
  return sparseQuery;
}

type SparqlQueryResult = { responseText: string; response: Response; key: string };
const inFlightSparqlRequests = new Map<string, Promise<SparqlQueryResult>>();

function parseSparqlResults(responseText: string): {
  head: { vars: string[] };
  results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
} | null {
  try {
    const parsed: unknown = JSON.parse(responseText);
    if (!parsed || typeof parsed !== "object") return null;
    const value = parsed as {
      head?: { vars?: unknown };
      results?: { bindings?: unknown };
    };
    if (!value.head || !Array.isArray(value.head.vars) ||
        !value.head.vars.every((item) => typeof item === "string") ||
        !value.results || !Array.isArray(value.results.bindings)) return null;
    for (const binding of value.results.bindings) {
      if (!binding || typeof binding !== "object" || Array.isArray(binding)) return null;
      for (const term of Object.values(binding as Record<string, unknown>)) {
        if (!term || typeof term !== "object" || Array.isArray(term) ||
            typeof (term as { value?: unknown }).value !== "string" ||
            typeof (term as { type?: unknown }).type !== "string") return null;
      }
    }
    return value as {
      head: { vars: string[] };
      results: { bindings: Record<string, { type?: string; value?: string; datatype?: string }>[] };
    };
  } catch {
    return null;
  }
}

async function querySparql(endpoint: string, query: string): Promise<SparqlQueryResult> {
  const sparqlUrl = endpoint;
  const key = queryCacheKey("sparql", sparqlUrl.toString(), query);
  const cached = getQueryCache<string>(key);
  if (cached !== undefined) {
    return {
      responseText: cached,
      response: new Response(cached, {
        status: 200,
        headers: { "Content-Type": "application/sparql-results+json; charset=utf-8" },
      }),
      key,
    };
  }

  // Coalesce identical upstream requests, but never cache here: the caller must
  // validate the operation-specific result before it becomes shared cache data.
  const pending = inFlightSparqlRequests.get(key);
  if (pending) return pending;

  const requestPromise = (async () => {
    const response = await fetch(sparqlUrl, {
      method: "POST",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded; charset=UTF-8",
        Accept: "application/sparql-results+json, application/json;q=0.9",
      },
      body: new URLSearchParams({ query }).toString(),
      cache: "no-store",
      signal: AbortSignal.timeout(20000),
    });
    return { responseText: await response.text(), response, key };
  })();
  inFlightSparqlRequests.set(key, requestPromise);
  try {
    return await requestPromise;
  } finally {
    if (inFlightSparqlRequests.get(key) === requestPromise) inFlightSparqlRequests.delete(key);
  }
}

export async function POST(request: Request) {
  logProxyCaller(request, "sparql.POST");
  try {
    const body = await request.json().catch(() => null);
    const endpointList = getConfiguredEndpoints();
    const endpointId = getSelectedEndpointId(request, endpointList);
    const selectedEndpoint = endpointList.find((item) => item.id === endpointId);
    const fctEndpoint = selectedEndpoint?.url;
    if (!fctEndpoint) {
      return NextResponse.json({ error: "No FCT endpoints are configured." }, { status: 500 });
    }

    // The Results pane compiles the authoritative FCT query tree to SPARQL on
    // the client and submits that SELECT here; unlike /fct, this path returns
    // the endpoint's SPARQL result bindings directly.
    if (body?.resultsQuery && typeof body.resultsQuery === "object") {
      const resultsQuery = body.resultsQuery.sparql;
      if (typeof resultsQuery !== "string" || !/^\s*(?:DEFINE\s+[^\n]+\s+)*SELECT\b/i.test(resultsQuery) ||
          !/\bAS\s+\?c1\b/i.test(resultsQuery) || /\b(?:INSERT|DELETE|CLEAR|LOAD|CREATE|DROP|MOVE|COPY|ADD)\b/i.test(resultsQuery)) {
        return NextResponse.json({ error: "A client-generated SELECT Results SPARQL query with ?c1 is required." }, { status: 400 });
      }
      const { responseText, response, key } = await querySparql(fctEndpoint, resultsQuery);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}.`, details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      if (!contentType.toLowerCase().includes("json")) {
        return NextResponse.json(
          { error: "Virtuoso SPARQL endpoint did not return JSON results.", details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed || !parsed.head.vars.includes("c1")) {
        return NextResponse.json({ error: "Virtuoso returned invalid Results SPARQL JSON (expected ?c1)." }, { status: 502 });
      }
      if (response.status === 200) setQueryCache(key, responseText);
      return NextResponse.json({ ...parsed, query: resultsQuery });
    }

    if (body?.facetValueCount && typeof body.facetValueCount === "object") {
      const sourceQuery = body.facetValueCount.sparql;
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The client-generated scalar count SPARQL query is required." }, { status: 400 });
      }
      const countQuery = validateFacetValueCountQuery(sourceQuery);
      if (!countQuery) {
        return NextResponse.json({ error: "The client must provide a scalar COUNT(...) AS ?ct SPARQL query." }, { status: 400 });
      }

      const { responseText, response, key } = await querySparql(fctEndpoint, countQuery);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}.`, details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      if (!contentType.toLowerCase().includes("json")) {
        return NextResponse.json(
          { error: "Virtuoso SPARQL endpoint did not return JSON results.", details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      const parsed = parseSparqlResults(responseText);
      const countValue = parsed?.results.bindings[0]?.ct?.value;
      const count = countValue !== undefined && /^\d+$/.test(countValue) ? Number(countValue) : NaN;
      if (!parsed || !parsed.head.vars.includes("ct") || parsed.results.bindings.length !== 1 ||
          !Number.isSafeInteger(count) || count < 0) {
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL count result." }, { status: 502 });
      }
      if (response.status === 200) setQueryCache(key, responseText);
      return NextResponse.json({ count, query: countQuery });
    }

    if (body?.facetIntersection && typeof body.facetIntersection === "object") {
      const sourceQuery = body.facetIntersection.sparql;
      const candidates = uniqueIris(body.facetIntersection.candidates, 500);
      if (!candidates) {
        return NextResponse.json({ error: "Autoconfigure candidates must be valid IRIs (maximum 500)." }, { status: 400 });
      }
      if (!candidates.length) return NextResponse.json({ uris: [] });
      if (typeof sourceQuery !== "string") {
        return NextResponse.json({ error: "The generated facet SPARQL query is required." }, { status: 400 });
      }
      const built = buildFacetIntersectionQuery(sourceQuery, candidates);
      if (!built) {
        return NextResponse.json({ error: "Could not safely add the high-frequency facets to the generated SPARQL query." }, { status: 400 });
      }

      const { responseText, response, key } = await querySparql(fctEndpoint, built.query);
      const contentType = response.headers.get("content-type") ?? "";
      if (!response.ok) {
        return NextResponse.json(
          { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}.`, details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      if (!contentType.toLowerCase().includes("json")) {
        return NextResponse.json(
          { error: "Virtuoso SPARQL endpoint did not return JSON results.", details: responseText.slice(0, 2000) },
          { status: 502 },
        );
      }
      const parsed = parseSparqlResults(responseText);
      if (!parsed || !parsed.head.vars.includes(built.variable)) {
        return NextResponse.json({ error: "Virtuoso returned an invalid SPARQL facet-intersection result." }, { status: 502 });
      }
      const bindings = parsed.results.bindings;
      const uris = [...new Set(bindings
        .map((binding) => binding[built.variable]?.value)
        .filter((value): value is string => typeof value === "string" && value.length > 0))];
      if (response.status === 200) setQueryCache(key, responseText);
      return NextResponse.json({ uris });
    }

    // Results enrichment is intentionally bounded to exact FCT result URIs and
    // the selected relationships, rather than accepting arbitrary SPARQL.
    const resources = uniqueIris(body?.resources, 100);
    const properties = uniqueIris(body?.properties ?? [], 100);
    const roles = uniqueIris(body?.roles ?? [], 100);
    if (!resources || resources.length === 0) {
      return NextResponse.json({ error: "One or more valid FCT result resource URIs are required." }, { status: 400 });
    }
    if (!properties || !roles) {
      return NextResponse.json({ error: "Selected property and role lists must contain valid IRIs (maximum 100 each)." }, { status: 400 });
    }
    if (properties.length + roles.length === 0) {
      return NextResponse.json({ head: { vars: [] }, results: { bindings: [] } });
    }

    const resourceValues = iriList(resources);
    const branches: string[] = [];
    if (properties.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(properties)} } ?resource ?property ?value . BIND("forward" AS ?direction) }`);
    }
    if (roles.length) {
      branches.push(`{ VALUES ?resource { ${resourceValues} } VALUES ?property { ${iriList(roles)} } ?value ?property ?resource . BIND("reverse" AS ?direction) }`);
    }
    const query = `SELECT DISTINCT ?resource ?property ?direction ?value WHERE { ${branches.join(" UNION ")} }`;
    const { responseText, response, key } = await querySparql(fctEndpoint, query);
    const contentType = response.headers.get("content-type") ?? "";
    if (!response.ok) {
      return NextResponse.json(
        { error: `Virtuoso SPARQL endpoint returned HTTP ${response.status}.`, details: responseText.slice(0, 2000) },
        { status: 502 },
      );
    }
    if (!contentType.toLowerCase().includes("json")) {
      return NextResponse.json(
        { error: "Virtuoso SPARQL endpoint did not return JSON results.", details: responseText.slice(0, 2000) },
        { status: 502 },
      );
    }

    if (!parseSparqlResults(responseText)) {
      return NextResponse.json({ error: "Virtuoso returned invalid SPARQL results JSON." }, { status: 502 });
    }
    if (response.status === 200) setQueryCache(key, responseText);
    return new NextResponse(responseText, {
      status: 200,
      headers: { "Content-Type": "application/sparql-results+json; charset=utf-8", "Cache-Control": "no-store" },
    });
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Could not query the SPARQL endpoint." },
      { status: 500 },
    );
  }
}