import { createPortal } from "react-dom";
import { ChevronLeft, ChevronRight, MousePointer2, Shrink, WandSparkles } from "lucide-react";
import { ResizablePanelGroup, ResizablePanel, ResizableHandle } from "@/components/ui/resizable";
import { ToggleGroup, ToggleGroupItem } from "@/components/ui/toggle-group";
import { Breadcrumb, BreadcrumbList, BreadcrumbItem, BreadcrumbSeparator } from "@/components/ui/breadcrumb";
import { useFctQuery } from "@/lib/fct-query-api";
import { buildWandQuery, type RecordTrailEdge, type WandedRecordEdge } from "@/lib/record-explorer-query";
import { toLabel } from "@/lib/uri-labels";
import { blankNodeRecordListValuesQuery, extendBlankNodeRecordQuery } from "@/lib/bnode-dom";
import { RecordSessionsController, type RecordSessionDescriptor, type RecordSessionIdentity, type RecordSessionsSnapshot } from "@/canvas/controllers/record-session-model";
import { useRecordPivotWorkspace } from "@/canvas/controllers/record-session-controller";
import { RightCanvasPanel, type RecordRdfaAction } from "@/canvas/right/pane";
import type { RecordPaneWorkspace } from "@/canvas/controllers/workspace-interfaces";
import type { RecordStatement } from "@/canvas/controllers/record-rdfa-decoration";
import "./record-source-highlight.css";

/** Fullscreen is a layout host only. Each Record is rendered by the same
 * RightCanvasPanel as Browse, with its own controller-owned workspace. */
type Props = { workspace: RecordPaneWorkspace; onClose: () => void };
type Mode = "pointer" | "wand";

type SessionViewProps = {
  session: RecordSessionDescriptor; index: number; slot: HTMLDivElement | null;
  base: RecordPaneWorkspace; controller: RecordSessionsController;
  mode: Mode; marked: readonly WandedRecordEdge[];
  followedSource: RecordStatement | null;
  onAction: (action: RecordRdfaAction) => void;
};

function BrowseSessionView({ session, index, slot, base, mode, marked, followedSource, onAction }: SessionViewProps) {
  return slot ? createPortal(<RightCanvasPanel workspace={base} sessionIndex={index}
    fullscreenPane interactionMode={mode} followedSource={followedSource}
    queuedProperties={marked.filter(item => item.recordIndex === index)} onRdfaAction={onAction} />, slot) : null;
}

function PivotSessionView({ session, index, slot, base, controller, mode, marked, followedSource, onAction }: SessionViewProps) {
  // This component stays mounted even when its pane is outside the three-pane
  // window; scrolling a breadcrumb does not discard its data or format state.
  const workspace = useRecordPivotWorkspace(session, controller, base);
  return slot ? createPortal(<RightCanvasPanel workspace={workspace} sessionIndex={index}
    fullscreenPane interactionMode={mode} followedSource={followedSource}
    queuedProperties={marked.filter(item => item.recordIndex === index)} onRdfaAction={onAction} />, slot) : null;
}

function makePivotIdentity(source: RecordSessionDescriptor, binding: RecordStatement,
  limit: number): RecordSessionIdentity {
  const identity: RecordSessionIdentity = { value: binding.value,
    termType: binding.termType, queryXml: source.identity.queryXml,
    ...(binding.datatype ? { datatype: binding.datatype } : {}),
    ...(binding.lang ? { lang: binding.lang } : {}) };
  if (binding.termType !== "bnode") return identity;
  // All bnode rebindings are generated by Maestro's existing DOM/FCT API.
  // Neither RDFa nor the fullscreen layout ever treats a _: label as an IRI.
  if (source.identity.termType === "uri") {
    identity.bnodeAnchor = { parent: source.identity.value, predicate: binding.predicate,
      direction: binding.direction === "property-of" ? "reverse" : "forward" };
    identity.bnodeQueryXml = blankNodeRecordListValuesQuery(source.identity.queryXml,
      binding.predicate, source.identity.value, limit, true,
      binding.direction === "property-of" ? "reverse" : "forward");
  } else if (source.identity.termType === "bnode" && source.identity.bnodeAnchor && source.identity.bnodeQueryXml) {
    identity.bnodeAnchor = source.identity.bnodeAnchor;
    identity.bnodeQueryXml = extendBlankNodeRecordQuery(source.identity.bnodeQueryXml,
      binding.predicate, binding.direction === "property-of" ? "reverse" : "forward", limit);
  } else {
    throw new Error("The blank-node value has no URI ancestor in this Record trail.");
  }
  return identity;
}

export function RecordExplorer({ workspace, onClose }: Props) {
  const { replaceTree } = useFctQuery();
  const queryTree = workspace.queryTree;
  const queryXml = workspace.queryXml;
  const first = workspace.selectedResult?.uri === workspace.selectedUri ? workspace.selectedResult :
    workspace.selectedGroupRecord?.uri === workspace.selectedUri ? workspace.selectedGroupRecord : null;
  const rootIdentity: RecordSessionIdentity = {
    value: workspace.selectedUri,
    termType: workspace.selectedRecordTermType,
    queryXml,
    ...(first?.datatype ? { datatype: first.datatype } : {}),
    ...(first?.lang ? { lang: first.lang } : {}),
  };
  const controllerRef = useRef<RecordSessionsController | null>(null);
  if (!controllerRef.current) controllerRef.current = new RecordSessionsController(rootIdentity);
  const controller = controllerRef.current;
  const [snapshot, setSnapshot] = useState<RecordSessionsSnapshot>(() => controller.snapshot());
  const [mode, setMode] = useState<Mode>("pointer");
  const [marked, setMarked] = useState<WandedRecordEdge[]>([]);
  const [slots, setSlots] = useState<Array<HTMLDivElement | null>>([null, null, null]);
  const slotRefs = useRef<Array<(element: HTMLDivElement | null) => void>>([]);
  if (!slotRefs.current.length) {
    slotRefs.current = [0,1,2].map(index => element => {
      setSlots(current => current[index] === element ? current : current.map((old, i) => i === index ? element : old));
    });
  }
  const [error, setError] = useState("");
  const [mounted, setMounted] = useState(false);
  useEffect(() => setMounted(true), []);
  // Fullscreen header starts collapsed, including session 0. This is only a
  // presentation preference: it does not gate automatic SHACL validation.
  useEffect(() => {
    const previous = workspace.recordControlsOpen;
    workspace.setRecordControlsOpen(false);
    return () => workspace.setRecordControlsOpen(previous);
  // One mount per fullscreen explorer; do not reopen on validation transitions.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
  const sessions = snapshot.sessions;
  const trail: RecordTrailEdge[] = sessions.slice(1).flatMap(session => session.via
    ? [{ predicate: session.via.predicate, direction: session.via.direction }] : []);

  const navigate = useCallback((index: number, binding: RecordStatement) => {
    const source = controller.snapshot().sessions[index];
    if (!source || !binding.value) return;
    try {
      const next = makePivotIdentity(source, binding, workspace.recordDescriptionQueryLimit);
      controller.appendPivot(next, { predicate: binding.predicate,
        direction: binding.direction, subjectSessionId: source.id }, index);
      setSnapshot(controller.snapshot());
      setMarked(current => current.filter(item => item.recordIndex <= index));
      setError("");
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : String(cause));
    }
  }, [controller, workspace.recordDescriptionQueryLimit]);

  const wand = useCallback((index: number, binding: RecordStatement) => {
    setMarked(current => current.some(item => item.recordIndex === index &&
        item.predicate === binding.predicate && item.direction === binding.direction)
      ? current.filter(item => !(item.recordIndex === index && item.predicate === binding.predicate && item.direction === binding.direction))
      : [...current, { recordIndex: index, predicate: binding.predicate, direction: binding.direction }]);
  }, []);
  const onAction = useCallback((action: RecordRdfaAction) => {
    if (action.intent === "pivot") navigate(action.sessionIndex, action.statement);
    else wand(action.sessionIndex, action.statement);
  }, [navigate, wand]);

  const focusBreadcrumb = (index: number) => {
    // Focusing ancestors changes only the viewport. Successors retain their
    // identity, data, formatter, and pending requests until another Shift-click.
    controller.focusSession(index);
    setSnapshot(controller.snapshot());
  };
  const slide = (direction: -1 | 1) => {
    controller.slide(direction);
    setSnapshot(controller.snapshot());
  };
  const close = () => {
    if (marked.length) replaceTree(buildWandQuery(queryTree, trail, marked));
    controller.shrink();
    onClose();
  };
  if (!mounted) return null;
  return createPortal(<div role="dialog" aria-modal="true" aria-label="Record explorer"
    className="maestro-record-explorer fixed inset-0 z-[100] flex flex-col bg-background text-foreground">
    <header className="flex shrink-0 flex-wrap items-center gap-3 border-b px-4 py-2">
      <div className="font-semibold">Record explorer</div>
      <ToggleGroup type="single" aria-label="Record interaction mode" value={mode}
        onValueChange={value => { if (value === "pointer" || value === "wand") setMode(value); }}
        className="rounded-md border p-0.5">
        <ToggleGroupItem value="pointer" title="Pointer mode" aria-label="Pointer mode"><MousePointer2 className="size-4" /></ToggleGroupItem>
        <ToggleGroupItem value="wand" title="Wand mode — queue properties for the live FCT query" aria-label="Wand mode"><WandSparkles className="size-4" /></ToggleGroupItem>
      </ToggleGroup>
      {marked.length > 0 && <span className="text-xs text-muted-foreground">{marked.length} queued properties</span>}
      {error && <span role="alert" className="max-w-md truncate text-xs text-destructive" title={error}>{error}</span>}
      <button type="button" onClick={close} title="Shrink to normal Record" aria-label="Shrink Record explorer"
        className="ml-auto rounded-md border p-2 hover:bg-accent"><Shrink className="size-4" /></button>
    </header>
    <Breadcrumb className="shrink-0 border-b px-3 py-2">
      <BreadcrumbList>
        {sessions.flatMap((session, index) => [
          ...(index ? [<BreadcrumbSeparator key={`sep-${session.id}`} />] : []),
          <BreadcrumbItem key={session.id}>
            {session.via && <span className="text-muted-foreground">{toLabel(session.via.predicate)}:</span>}
            <button type="button" onClick={() => focusBreadcrumb(index)}
              className={`rounded px-2 py-1 hover:bg-accent ${index >= snapshot.visibleStart && index < snapshot.visibleStart + 3
                ? "bg-accent font-semibold" : "text-muted-foreground"}`}>
              {toLabel(session.identity.value)}
            </button>
          </BreadcrumbItem>,
        ])}
      </BreadcrumbList>
    </Breadcrumb>
    <div className="flex min-h-0 flex-1 items-stretch">
      <button type="button" aria-label="Previous Record window" title="Previous Record"
        disabled={snapshot.visibleStart === 0} onClick={() => slide(-1)}
        className="border-r p-1 disabled:opacity-30"><ChevronLeft className="size-4" /></button>
      <div className="min-w-0 flex-1" onWheel={event => {
        if (Math.abs(event.deltaX) > Math.abs(event.deltaY) && Math.abs(event.deltaX) > 12)
          slide(event.deltaX < 0 ? -1 : 1);
      }}>
        <ResizablePanelGroup direction="horizontal" className="h-full">
          {[0,1,2].flatMap((index) => [
            ...(index ? [<ResizableHandle key={`handle-${index}`} withHandle />] : []),
            <ResizablePanel key={index} defaultSize={100/3} minSize={15}>
              <div ref={slotRefs.current[index]} className="h-full min-h-0 min-w-0 overflow-hidden">
                {!sessions[snapshot.visibleStart + index] &&
                  <div className="flex h-full items-center justify-center px-4 text-center text-sm text-muted-foreground">Shift-click a Record value in the preceding pane</div>}
              </div>
            </ResizablePanel>,
          ])}
        </ResizablePanelGroup>
      </div>
      <button type="button" aria-label="Next Record window" title="Next Record"
        disabled={snapshot.visibleStart + 3 >= sessions.length} onClick={() => slide(1)}
        className="border-l p-1 disabled:opacity-30"><ChevronRight className="size-4" /></button>
    </div>
    {/* Session controllers remain mounted even when their Record is outside
        the visible three-pane window. Only their *view portals* are hidden. */}
    {sessions.map((session, index) => {
      const paneIndex = index - snapshot.visibleStart;
      const slot = paneIndex >= 0 && paneIndex < 3 ? slots[paneIndex] : null;
      const props: SessionViewProps = { session, index, slot, base: workspace,
        controller, mode, marked, followedSource: controller.followedSource(session.id), onAction };
      return index === 0 ? <BrowseSessionView key={session.id} {...props} />
        : <PivotSessionView key={session.id} {...props} />;
    })}
  </div>, document.body);
}
