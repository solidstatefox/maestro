/** Read-only SPARQL generated by graph-provided rules. Updates and SERVICE
 * federation are not permitted by this client executor; endpoint ACLs still
 * enforce actual graph access. */
function readQuery(value:string,kind:"SELECT"|"ASK"):string{
  const query=value.trim();
  if(!query||query.length>20000)throw new Error(`Invalid ${kind} query in OTC rule.`);
  // Strip the entire SPARQL PREFIX/BASE prolog. Then mask literal and
  // IRI content so keywords inside values are not interpreted as operations.
  const noProlog=query.replace(/^(?:\s*(?:PREFIX\s+(?:[A-Za-z_][\w-]*)?:\s*<[^>]+>|BASE\s*<[^>]+>))*/i, "").trimStart();
  const stripped=noProlog.replace(/"""[\s\S]*?"""|'''[\s\S]*?'''|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|<[^>]*>|#[^\r\n]*/g," ").trim();
  if(!new RegExp(`^${kind}\\b`,"i").test(stripped) ||
    /\b(?:SERVICE|LOAD|INSERT|DELETE|CLEAR|CREATE|DROP|MOVE|COPY|ADD|WITH|USING|FROM|DESCRIBE|CONSTRUCT|VALUES\s*\{|GRAPH\s*\?)/i.test(stripped))
    throw new Error(`OTC ${kind} query contains unsupported operations.`);
  return query;
}
async function sourceQuery(ctx:PersonalContext,query:string,graph:string|undefined,kind:"SELECT"|"ASK",signal?:AbortSignal):Promise<{rows:Row[];boolean?:boolean}>{
  check(signal);readQuery(query,kind);
  // Use the original /sparql route. A supplied source graph is expressed as
  // SPARQL dataset scope, not a hidden HTTP/proxy operation.
  const requested=kind==="ASK"?query.replace(/\bASK(?:\s+WHERE)?\s*\{/i,"SELECT (true AS ?otcAskMatched) WHERE {")+' LIMIT 1':query;
  if(kind==="ASK"&&requested===query+' LIMIT 1')throw new Error("Unsupported OTC ASK syntax.");
  const scoped=graph?requested.replace(/\bWHERE\b/i,`FROM ${iri(graph)} WHERE`):requested;
  const response=await fetch("/proxy/api/sparql",{method:"POST",credentials:"same-origin",cache:"no-store",signal,
    headers:{"Content-Type":"application/json"},body:JSON.stringify({addr:ctx.addr,query:scoped})});
  const text=await response.text();
  if(!response.ok)throw new Error(`OTC SPARQL ${kind} failed (HTTP ${response.status}): ${text.slice(0,250)}`);
  if(text.length>2_000_000)throw new Error("OTC SPARQL response exceeds size limit.");
  const data=JSON.parse(text) as {boolean?:unknown;results?:{bindings?:Row[]};incomplete?:boolean};
  if(data.incomplete)throw new Error("OTC SPARQL query returned incomplete results.");
  if(kind==="ASK"){
    if(!Array.isArray(data.results?.bindings))throw new Error("OTC ASK conversion did not return SELECT bindings.");
    return {rows:[],boolean:data.results.bindings.length>0};
  }
  if(!Array.isArray(data.results?.bindings))throw new Error("OTC SELECT did not return bindings.");
  return {rows:data.results.bindings};
}
async function approved(ctx:PersonalContext,rulesGraph:string,provider:string,signal?:AbortSignal):Promise<void>{
  const matches=await selectPersonal(`SELECT ?isProvider ?approved WHERE {
    GRAPH ${iri(rulesGraph)} { ${iri(provider)} a <${MUI}Provider> . BIND(true AS ?isProvider) }
    OPTIONAL { GRAPH <${ctx.base}/status> { ${iri(provider)} <${MUI}status> <${MUI}Approved> . BIND(true AS ?approved) } }
  } LIMIT 2`,ctx,signal);
  if(!matches.length)throw new Error("Selected OTC transcoder is not a provider in the requested rules graph.");
  if(matches.some(row=>row.approved?.value==="true"||row.approved?.value==="1"))return;
  const effective=await readClientPolicyApprovals([provider],signal);
  if(effective[0]?.status!=="Approved")
    throw new Error(`Transcoder ${provider} is not Approved in your personal graph.`);
}
async function rules(ctx:PersonalContext,rulesGraph:string,transcoder:string,signal?:AbortSignal):Promise<Rule[]>{
  const rows=await selectPersonal(`PREFIX otc:<${OTC}> PREFIX mui:<${MUI}>
SELECT ?rule ?ask ?select ?target ?survey ?template ?assumption ?validator WHERE {
 GRAPH ${ref(rulesGraph)} { ${ref(transcoder)} a otc:Transcoder ; otc:hasRule ?rule .
 OPTIONAL { ${ref(transcoder)} mui:accepts ?validator }
 ?rule otc:select ?select ; otc:query ?survey ; otc:template ?template .
 OPTIONAL { ?rule otc:ask ?ask } OPTIONAL { ?rule otc:target ?target }
 OPTIONAL { ?rule otc:assume ?assumption }
 } } LIMIT 100`,ctx,signal);
  const map=new Map<string,Rule>();
  for(const row of rows){const id=row.rule?.value;if(!id||!row.select?.value||!row.survey?.value||!row.template?.value)continue;
    let item=map.get(id);if(!item){item={id,select:row.select.value,query:row.survey.value,template:row.template.value,
      ask:row.ask?.value??"",target:row.target?.value??"",validator:row.validator?.value??"",assumptions:[]};map.set(id,item);}
    if(row.assumption?.value&&!item.assumptions.includes(row.assumption.value))item.assumptions.push(row.assumption.value);
  }
  if(!map.size)throw new Error("Selected OTC transcoder has no executable rules.");
  if(map.size>8)throw new Error("OTC execution is limited to eight rules per transcoder.");
  return [...map.values()];
}
async function shape(ctx:PersonalContext,graph:string,shapeUri:string,signal?:AbortSignal):Promise<Shape>{
  const rows=await selectPersonal(`PREFIX sh:<${SH}> PREFIX mui:<${MUI}>
SELECT ?class ?property ?path ?minCount ?datatype ?nodeKind ?minLength ?hasValue WHERE {
 GRAPH ${ref(graph)} { ${ref(shapeUri)} a mui:InputShape .
 OPTIONAL { ${ref(shapeUri)} sh:class ?class }
 OPTIONAL { ${ref(shapeUri)} sh:property ?property . ?property sh:path ?path .
 OPTIONAL { ?property sh:minCount ?minCount } OPTIONAL { ?property sh:datatype ?datatype }
 OPTIONAL { ?property sh:nodeKind ?nodeKind } OPTIONAL { ?property sh:minLength ?minLength }
 OPTIONAL { ?property sh:hasValue ?hasValue } } }
} LIMIT 100`,ctx,signal);
  if(!rows.length)throw new Error(`SHACL shape ${shapeUri} is missing.`);
  const classes=new Set<string>(),constraints=new Map<string,Constraint>();
  for(const row of rows){const classIri=row.class?.value;if(classIri)classes.add(classIri);
    const id=row.property?.value;if(!id)continue;
    const path=row.path?.value;
    if(!path||row.path?.type!=="uri")throw new Error("SHACL path must be an IRI.");
    if(constraints.has(id))continue;
    const minCount=row.minCount?Number(row.minCount.value):0,minLength=row.minLength?Number(row.minLength.value):undefined;
    if(!Number.isSafeInteger(minCount)||minCount<0||(minLength!==undefined&&(!Number.isSafeInteger(minLength)||minLength<0)))
      throw new Error("Invalid OTC SHACL count or length.");
    const boundValue=row.hasValue;
    let hasValue:OtcTerm|undefined;
    if(boundValue){
      const {type,value,datatype}=boundValue;
      if(typeof type!=="string"||typeof value!=="string")
        throw new Error("Invalid OTC SHACL hasValue binding.");
      hasValue={type,value,...(datatype?{datatype}:{})};
    }
    const item:Constraint={path,minCount,
      ...(minLength!==undefined?{minLength}:{}),...(row.datatype?.value?{datatype:row.datatype.value}:{}),
      ...(row.nodeKind?.value?{nodeKind:row.nodeKind.value}:{}),...(hasValue?{hasValue}:{})};
    if(item.nodeKind&&item.nodeKind!==`${SH}Literal`)throw new Error("Unsupported OTC SHACL node kind (fails closed).");
    constraints.set(id,item);
  }
  if(!classes.size||!constraints.size)throw new Error("OTC SHACL shape lacks required constraints.");
  return {uri:shapeUri,classes:[...classes],properties:[...constraints.values()]};
}
const same=(a:OtcTerm,b:OtcTerm):boolean=>a.type===b.type&&a.value===b.value&&
  (a.type!=="literal"&&a.type!=="typed-literal"||
   ((a.datatype??`${XSD}string`)===(b.datatype??`${XSD}string`) && (a["xml:lang"]??"")===(b["xml:lang"]??"")));
async function validate(ctx:PersonalContext,focus:OtcTerm|undefined,s:Shape,sourceGraph:string|undefined,signal?:AbortSignal){
  if(!focus||focus.type!=="uri"||!good(focus.value))return {conforms:false,violations:["OTC SHACL requires an IRI ?message focus node."]};
  const predicates=[...new Set([`${RDF}type`,...s.properties.map(p=>p.path)])];
  const query=`SELECT ?p ?v WHERE { ${iri(focus.value)} ?p ?v . FILTER (?p IN (${predicates.map(iri).join(", ")})) }`;
  const {rows}=await sourceQuery(ctx,query,sourceGraph,"SELECT",signal);
  const found=new Map<string,OtcTerm[]>();for(const row of rows)if(row.p&&row.v)found.set(row.p.value,[...(found.get(row.p.value)??[]),row.v]);
  const failures:string[]=[];
  for(const name of s.classes)if(!(found.get(`${RDF}type`)??[]).some(t=>t.type==="uri"&&t.value===name))failures.push(`Missing rdf:type ${name}`);
  for(const p of s.properties){const values=found.get(p.path)??[];
    if(values.length<p.minCount)failures.push(`${p.path}: sh:minCount ${p.minCount}`);
    if(p.hasValue&&!values.some(t=>same(t,p.hasValue!)))failures.push(`${p.path}: sh:hasValue missing`);
    for(const t of values){const lit=t.type==="literal"||t.type==="typed-literal";
      if(p.nodeKind===`${SH}Literal`&&!lit)failures.push(`${p.path}: requires literal`);
      if(p.datatype&&(!lit||(t.datatype??`${XSD}string`)!==p.datatype||Boolean(t["xml:lang"])))failures.push(`${p.path}: wrong datatype`);
      if(p.minLength!==undefined&&(!lit||[...t.value].length<p.minLength))failures.push(`${p.path}: sh:minLength ${p.minLength}`);
    }
  }
  return {conforms:!failures.length,violations:failures};
}
async function staticSkill(signal?:AbortSignal):Promise<string>{
  const response=await fetch("/maestro-seed/otc-survey-skill.md",{signal,cache:"force-cache"});
  if(!response.ok)throw new Error("Missing static OTC survey instructions. Run the prebuild generator.");
  const text=await response.text();if(!text||text.length>30_000)throw new Error("Invalid OTC survey instructions.");return text;
}
async function survey(rule:Rule,row:Row,transcoder:string,activity:AssistantActivity[],
  progress:(event:ClientOtcProgress)=>void,instruction:string|undefined,budget:QwenThinkingBudget,signal?:AbortSignal):Promise<Row>{
  check(signal);
  const skill=await staticSkill(signal);
  const metadata=[`@prefix otc: <${OTC}> .`,`@prefix mui: <${MUI}> .`,
    `${ref(transcoder)} a otc:Transcoder, mui:Provider ; otc:hasRule _:survey .`,
    `_:survey otc:query ${JSON.stringify(rule.query)} .`,
    ...(rule.ask?[`_:survey otc:ask ${JSON.stringify(rule.ask)} .`]:[]),
    `_:survey otc:select ${JSON.stringify(rule.select)} .`,
    ...(rule.validator?[`${ref(transcoder)} mui:accepts ${ref(rule.validator)} .`]:[]),
    ...rule.assumptions.map(t=>`_:survey otc:assume ${JSON.stringify(t)} .`)].join("\n");
  const prompt=[`Directive: ${OTC}Transcoder`,`Transcoder RDF metadata (template intentionally excluded):`,metadata,
    `SPARQL input bindings (authoritative): ${JSON.stringify(row)}`,`Survey: ${rule.query}`,
    ...(instruction?[`User transcode request (context, not a replacement for the survey): ${instruction.slice(0,2000)}`]:[])].join("\n\n");
  const log:AssistantActivity={id:crypto.randomUUID(),createdAt:new Date().toISOString(),
    source:`OTC / ${transcoder.split("#").pop()||"Transcoder"} / ${rule.id.split("#").pop()||"Survey"}`,
    prompt,response:"",status:"error"};activity.push(log);
  const payload={model:"qwen/qwen3.8-27b",...qwenThinkingOptions(budget,1400),stream:true,
    stream_options:{include_usage:true},temperature:0,
    messages:[{role:"system",content:skill},{role:"user",content:prompt}]};
  const response=await callOpenAiChatCompletions(payload,signal);
  if(!response.ok)throw new Error(`IteraCompute survey returned HTTP ${response.status}.`);
  if(!response.body)throw new Error("OTC survey returned no SSE stream.");
  let raw="",reasoning="",buffer="",ended=false;
  let usage:{prompt_tokens?:number;completion_tokens?:number;total_tokens?:number}|undefined;
  const approximateInput=Math.ceil((skill.length+prompt.length)/4);
  let lastUpdate=0;
  const publish=(force=false)=>{const now=Date.now();if(!force&&now-lastUpdate<200)return;lastUpdate=now;
    const input=usage?.prompt_tokens??approximateInput,output=usage?.completion_tokens??Math.ceil((raw.length+reasoning.length)/4);
    progress({step:"qwen",status:"running",rule:rule.id,message:row.message?.value,detail:"Streaming OTC survey response",live:{
      reasoning:reasoning.slice(-3000),content:raw.slice(-3000),input,output,total:usage?.total_tokens??input+output,
      estimated:usage?.total_tokens===undefined,phase:raw?"response":reasoning?"reasoning":"waiting",thinkingBudget:budget,
      reasoningTokens:Math.ceil(reasoning.length/4)}});
  };
  const event=(text:string)=>{const data=text.split(/\r?\n/).filter(s=>s.startsWith("data:")).map(s=>s.slice(5).trimStart()).join("\n").trim();
    if(!data)return;if(data==="[DONE]"){ended=true;return;}
    const packet=JSON.parse(data) as {error?:{message?:string};usage?:typeof usage;choices?:Array<{delta?:{content?:string;reasoning_content?:string;reasoning?:string};message?:{content?:string}}>} ;
    if(packet.error)throw new Error(packet.error.message??"Survey stream error.");
    if(packet.usage)usage=packet.usage;
    for(const entry of packet.choices??[]){raw+=entry.delta?.content??entry.message?.content??"";
      reasoning+=entry.delta?.reasoning_content??entry.delta?.reasoning??"";}
    publish();
  };
  const reader=response.body.getReader(),decoder=new TextDecoder();
  try{publish(true);while(true){check(signal);const {done,value}=await reader.read();buffer+=decoder.decode(value,{stream:!done});
      let boundary:RegExpExecArray|null;while((boundary=/\r?\n\r?\n/.exec(buffer))){event(buffer.slice(0,boundary.index));buffer=buffer.slice(boundary.index+boundary[0].length);}
      if(done)break;}
    if(buffer.trim())event(buffer);
  }catch(error){await reader.cancel().catch(()=>{});throw error;}finally{reader.releaseLock();}
  if(!ended&&!raw.trim())throw new Error("OTC survey ended without an answer.");
  publish(true);log.response=raw.trim();if(!log.response)throw new Error("OTC survey returned empty bindings.");
  if(usage)log.usage={input:usage.prompt_tokens,output:usage.completion_tokens,total:usage.total_tokens};
  const clean=raw.trim().replace(/^```(?:json)?\s*/i,"").replace(/\s*```$/,"");
  const parsed=JSON.parse(clean) as {bindings?:Row};
  if(!parsed.bindings?.resp)throw new Error("OTC survey did not bind reserved ?resp.");
  const result={...row};
  for(const [name,term] of Object.entries(parsed.bindings)){
    if(!/^[A-Za-z_][\w]*$/.test(name)||name in row||!term||!(["uri","literal"].includes(term.type))||
       typeof term.value!=="string"||term.value.length>12000)throw new Error(`Invalid OTC survey binding ?${name}.`);
    if(term.type==="uri")iri(term.value);
    result[name]={type:term.type,value:term.value};
  }
  log.status="success";return result;
}
async function writeTriples(graph:string,triples:ClientRdfTriple[],signal?:AbortSignal){
  for(let i=0;i<triples.length;i+=120){check(signal);await updatePersonal(clientRdfInsert(graph,triples.slice(i,i+120)),signal);}
}

/** Two-stage maximum: only validated rows call the LLM. All status approvals
 * are read from RDF; all writes happen at the graph server, never on the host. */
export async function runClientTranscoder(input:ClientOtcOptions):Promise<ClientOtcResult>{
  const {rulesGraph,transcoder,namespace,sourceGraph,dryRun,signal}=input;
  [rulesGraph,transcoder,namespace,...(sourceGraph?[sourceGraph]:[])].forEach(iri);
  if(namespace.includes("#"))throw new Error("OTC output namespace must not contain #.");
  const ctx=await personalContext(),runGraph=`${namespace}#${crypto.randomUUID()}`;
  const progress=(event:ClientOtcProgress)=>input.onProgress?.(event);
  const trace:RuleTrace[]=[],successors:SuccessorTrace[]=[],triples:ClientRdfTriple[]=[],activity:AssistantActivity[]=[];
  let current=transcoder,currentSourceGraph=sourceGraph;
  const staging:string[]=[];
  try{
    await approved(ctx,rulesGraph,current,signal);
    let allRules=await rules(ctx,rulesGraph,current,signal);
    for(let depth=0;depth<2;depth++){
      const output:ClientRdfTriple[]=[];
      for(const rule of allRules){check(signal);
        if(!rule.validator)throw new Error(`OTC rule ${rule.id} has no input SHACL shape.`);
        progress({step:"shape",status:"running",rule:rule.id,shape:rule.validator,detail:"Loading SHACL shape"});
        const s=await shape(ctx,rulesGraph,rule.validator,signal);
        progress({step:"shape",status:"success",rule:rule.id,shape:s.uri,detail:"SHACL input shape loaded"});
        let eligible:boolean|undefined;
        if(rule.ask){eligible=(await sourceQuery(ctx,readQuery(rule.ask,"ASK"),currentSourceGraph,"ASK",signal)).boolean;
          progress({step:"ask",status:eligible?"success":"warning",rule:rule.id,detail:`Input ASK: ${eligible?"true":"false"}`});
          if(!eligible){trace.push({rule:rule.id,rows:0,turtle:[],bindings:[],ask:false,skippedInvalid:[]});continue;}}
        const selected=(await sourceQuery(ctx,readQuery(rule.select,"SELECT"),currentSourceGraph,"SELECT",signal)).rows;
        const rows=selected.slice(0,5);
        progress({step:"select",status:"success",rule:rule.id,detail:`SPARQL SELECT: ${selected.length} rows; processing ${rows.length}`});
        const snippets:string[]=[],bindings:Row[]=[],skippedInvalid:Array<{message:string;violations:string[]}>=[];
        let checked=0,passed=0;
        for(const row of rows){check(signal);
          const checkedRow=await validate(ctx,row.message,s,currentSourceGraph,signal);checked++;
          if(!checkedRow.conforms){skippedInvalid.push({message:row.message?.value??"(unbound)",violations:checkedRow.violations});
            progress({step:"shacl",status:"warning",rule:rule.id,shape:s.uri,detail:"Input SHACL violation; skipped",
              message:row.message?.value,violations:checkedRow.violations,counts:{checked,passed,failed:checked-passed}});continue;}
          passed++;
          progress({step:"shacl",status:"success",rule:rule.id,shape:s.uri,detail:"Input conforms to SHACL",message:row.message?.value,counts:{checked,passed}});
          const joined=await survey(rule,row,current,activity,progress,input.instruction,input.thinkingBudget??0,signal);
          progress({step:"qwen",status:"success",rule:rule.id,message:row.message?.value,detail:"Survey bindings received"});
          const turtle=await renderOtcLiquid(rule.template,joined);
          const parsed=await parseClientRdf(turtle,".ttl",runGraph);
          if(triples.length+output.length+parsed.length>300)throw new Error("OTC run exceeds the 300-triple output budget.");
          const blanks=new Map<string,string>();
          const b=(term:ClientRdfTriple["subject"]):ClientRdfTriple["subject"]=>{
            if(term.termType!=="BlankNode")return term;let id=blanks.get(term.value);
            if(!id){id=`urn:maestro:otc:blank:${crypto.randomUUID()}`;blanks.set(term.value,id);}return {termType:"NamedNode",value:id};};
          output.push(...parsed.map(t=>({subject:b(t.subject),predicate:t.predicate,object:b(t.object)})));
          snippets.push(turtle);bindings.push(joined);
          progress({step:"liquid",status:"success",rule:rule.id,message:row.message?.value,
            detail:`Liquid rendered ${parsed.length} RDF triples`,counts:{triples:parsed.length}});
        }
        progress({step:"shacl",status:skippedInvalid.length?"warning":"success",rule:rule.id,shape:s.uri,
          detail:`SHACL summary: ${passed}/${checked} passed`,counts:{checked,passed,failed:checked-passed}});
        trace.push({rule:rule.id,rows:rows.length,turtle:snippets,bindings,skippedInvalid,
          ...(eligible===undefined?{}:{ask:eligible})});
      }
      triples.push(...output);
      if(!output.length||depth===1||input.followSuccessors===false||!allRules.some(r=>r.target.trim()))break;
      const stageGraph=`${namespace}#otc-stage-${crypto.randomUUID()}`;
      staging.push(stageGraph);await writeTriples(stageGraph,output,signal);
      const choices=new Map<string,string>();
      for(const rule of allRules){if(!rule.target.trim())continue;
        const rows=(await sourceQuery(ctx,readQuery(rule.target,"SELECT"),rulesGraph,"SELECT",signal)).rows;
        for(const row of rows){if(row.nextTranscoder?.type!=="uri"||row.shape?.type!=="uri")
          throw new Error("OTC target query must project ?nextTranscoder and ?shape as IRIs.");
          if(row.nextTranscoder.value!==current)choices.set(row.nextTranscoder.value,row.shape.value);
          if(choices.size>50)throw new Error("Too many OTC successor candidates.");}}
      let advanced=false;
      for(const [candidate,shapeUri] of [...choices.entries()].sort(([a],[b])=>a.localeCompare(b))){check(signal);
        const candidateRules=await rules(ctx,rulesGraph,candidate,signal);
        if(candidateRules.some(r=>r.validator!==shapeUri)){
          successors.push({transcoder:candidate,shape:shapeUri,conforms:false,reason:"Shape not linked to successor."});continue;}
        const candidateShape=await shape(ctx,rulesGraph,shapeUri,signal);
        const subjects=[...new Set(output.filter(t=>t.subject.termType==="NamedNode").map(t=>t.subject.value))];
        let conforms=false;
        for(const subject of subjects){const v=await validate(ctx,{type:"uri",value:subject},candidateShape,stageGraph,signal);
          if(v.conforms){conforms=true;break;}}
        if(!conforms){successors.push({transcoder:candidate,shape:shapeUri,conforms:false,reason:"Generated RDF fails successor shape."});continue;}
        const eligibleChecks=await Promise.all(candidateRules.map(async rule=>!rule.ask.trim()||
          (await sourceQuery(ctx,readQuery(rule.ask,"ASK"),stageGraph,"ASK",signal)).boolean===true));
        const eligible=eligibleChecks.some(Boolean);
        successors.push({transcoder:candidate,shape:shapeUri,conforms:true,ask:eligible});
        if(!eligible)continue;
        await approved(ctx,rulesGraph,candidate,signal);
        current=candidate;allRules=candidateRules;currentSourceGraph=stageGraph;advanced=true;break;
      }
      if(!advanced)break;
    }
    if(!triples.length)return {ok:true,published:false,reason:"No eligible or SHACL-valid input rows.",trace,successors,activity};
    if(dryRun)return {ok:true,published:false,dryRun:true,runGraph,tripleCount:triples.length,
      turtle:trace.flatMap(t=>t.turtle).join("\n\n"),trace,successors,activity};
    if(await personalExists(`GRAPH ${iri(runGraph)} { ?s ?p ?o }`,ctx,signal))throw new Error("OTC destination graph already exists.");
    await writeTriples(runGraph,triples,signal);
    if(!await personalExists(`GRAPH ${iri(runGraph)} { ?s ?p ?o }`,ctx,signal))throw new Error("OTC output was not visible after publication.");
    return {ok:true,published:true,runGraph,tripleCount:triples.length,
      turtle:trace.flatMap(t=>t.turtle).join("\n\n"),trace,successors,activity};
  }finally{
    for(const graph of staging.reverse()){
      try{progress({step:"cleanup",status:"running",detail:"Removing temporary OTC graph"});await updatePersonal(`CLEAR GRAPH ${iri(graph)}`);
        progress({step:"cleanup",status:"success",detail:"Temporary OTC graph removed"});}
      catch(error){progress({step:"cleanup",status:"error",detail:`Could not remove temporary OTC graph. Clean up manually: ${error instanceof Error ? error.message : String(error)}`});}
    }
    if(activity.length)await appendAssistantActivity(activity).catch(()=>{});
  }
}
