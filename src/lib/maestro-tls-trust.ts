const SUPPLEMENTAL_CERTIFICATES = [ISRG_ROOT_YR_BY_X1, ISRG_ROOT_YE_BY_X2] as const;
let installed = false;

/** Run once before any upstream HTTPS fetch on the Node server (including on Vercel). */
export function registerMaestroTlsTrust(): void {
  if (installed) return;
  // The Node 24 runtime provides these APIs. A structural type keeps this
  // compatible with projects whose @types/node lags behind their runtime.
  const caStore = tls as typeof tls & {
    getCACertificates?: (type: "default") => string[];
    setDefaultCACertificates?: (certificates: string[]) => void;
  };
  if (typeof caStore.getCACertificates !== "function" || typeof caStore.setDefaultCACertificates !== "function") {
    throw new Error("Maestro TLS trust supplements require Node.js 24.5+ (or 22.19+)");
  }
  const current = caStore.getCACertificates("default");
  // These roots are accepted only if their X1/X2 cross-signatures verify against
  // the existing trusted CA bundle. This prevents accidentally shipping an
  // unrelated or malformed trust anchor in this source file.
  const roots = current.map((pem) => new X509Certificate(pem));
  for (const pem of SUPPLEMENTAL_CERTIFICATES) {
    const cert = new X509Certificate(pem);
    const parent = roots.find((root) => root.subject === cert.issuer && cert.checkIssued(root) && cert.verify(root.publicKey));
    if (!parent || !cert.ca) {
      throw new Error("Maestro TLS CA supplement did not verify against the existing trust store");
    }
  }
  caStore.setDefaultCACertificates([...current, ...SUPPLEMENTAL_CERTIFICATES]);
  installed = true;
}
